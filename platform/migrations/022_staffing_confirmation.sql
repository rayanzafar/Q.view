-- ═══ تسكينٌ يؤكّده مدير الموظف ═══════════════════════════════════════════════════════════════
--
-- بلسان المالك: «مو إعارة، إنما تسكين — وعشان المدير يأكّد أن الموظف شغّال على هذا الشي، مو أي
-- أحد يسكّن أي أحد في أي مكان. هذا بس، مدير القطاع ما يحتاج».
--
-- فالغرض **تأكيد** لا استئذانٌ في إعارة: من يضمّ زميلاً من إدارةٍ أخرى إلى فرصته يعرف أنه يريده،
-- والذي لا يعرفه أن الرجل مشغولٌ بشيءٍ آخر تعرفه إدارتُه. فيصل الطلب إلى مديره فيؤكّد أو يردّ —
-- خطوةٌ واحدة، ولا ثانيةَ فوقها.
--
-- ── لماذا لا جدول «طلب تسكين» جديد ────────────────────────────────────────────────────────
-- الاعتمادات في المنصة لها محرّكها وجداولها وصفحتها منذ أول إصدار (`approval_request` وأخواتها).
-- وجدولٌ ثانٍ يعني صندوقَ واردٍ ثانياً للمعتمِد، وسجلَّ إجراءاتٍ ثانياً، وشاشةً ثانية — ثم يوماً
-- يسأل فيه أحدهم: «أين أرى ما ينتظرني» فيكون الجواب «في مكانين». صندوقٌ واحد أو لا يُقرأ أصلاً.
--
-- والناقص في المحرّك شيءٌ واحد: **التوجيه إلى شخصٍ بعينه**. الخطوات اليوم تُوجَّه بالدور والنطاق
-- (`approval_step.approver_role`) — وهو الصحيح للاعتمادات المالية: «أي قائد قطاع» يعتمد. أما هنا
-- فالمعتمِد ليس دوراً بل إنساناً: **مدير هذا الموظف بعينه**. فعمودٌ اختياري يحمل الشخص، ومتى كان
-- فارغاً بقي التوجيه بالدور كما هو — لا مسار قديم يتغيّر.
ALTER TABLE approval_request ADD COLUMN assignee_user_id TEXT REFERENCES app_user(id);
CREATE INDEX IF NOT EXISTS ix_appr_assignee ON approval_request(assignee_user_id, status);

-- ── وحالة العضوية ────────────────────────────────────────────────────────────────────────────
-- عضويةٌ تنتظر تأكيداً ليست عضويةً بعد: لو كُتبت نشطةً ثم رُدّ الطلب لكان الرجل قد ظهر في الفريق
-- وحُسب في تحميله يوماً أو يومين بلا وجه حق. والفراغ يعني «نشطة» — وهو ما عليه كل صفٍّ قائم،
-- فلا ترحيلَ بيانات ولا تفسيرَ جديد لما هو مكتوب.
ALTER TABLE membership ADD COLUMN status TEXT;
CREATE INDEX IF NOT EXISTS ix_membership_status ON membership(status);
