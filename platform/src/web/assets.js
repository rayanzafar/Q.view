// ═══ بصمةُ الملفّات الساكنة — كي لا يبقى المتصفّح على شيفرةٍ قديمة بعد النشر ═══════════════
//
// العطل بلسان المالك: «ولا أقدر أسوي حفظ». والزرّ كان معروضاً على شاشته فعلاً، والخدمة خلفه
// تعمل وتردّ ٢٠٠ — لكن **الضغط لا يفعل شيئاً**. والسبب ليس في الصلاحيات ولا في الخدمة:
//
//   `/static/pages/opps.js` يُخدَّم بـ `Cache-Control: max-age=3600` وبلا رقم نسخةٍ في عنوانه.
//   فبعد كل نشر تصل الصفحةُ جديدةً (تُبنى في كل طلب) ويصل ملفّ الشيفرة **قديماً من ذاكرة
//   المتصفّح** — ساعةً كاملة. فيرى المستخدم زرّاً لا معالج له، ويضغط ولا يحدث شيء، ولا رسالة
//   خطأ تقول لماذا. وهذا يصيب كل زرّ جديد في كل صفحة بعد كل نشر، لا هذه الميزة وحدها.
//
// العلاج القياسي: بصمةٌ في العنوان تتغيّر متى تغيّر الملف (`?v=…`). فالعنوان الجديد لا يوجد
// في ذاكرة المتصفّح أصلاً فيُجلَب حتماً، والعنوان الذي لم يتغيّر يبقى مخبَّأً بكامل فائدته —
// أي أننا نكسب الطزاجة بلا أن نخسر التخبئة.
//
// والبصمة من زمن تعديل الملف لا من محتواه: المنصة بلا خطوة بناء (قرار معماري قائم)، وقراءةُ
// كل ملف وتجزئتُه عند الإقلاع كلفةٌ بلا مقابل — وزمن التعديل يتغيّر مع كل نشر لأن الصورة
// تُبنى من جديد. وتُقرأ **مرة واحدة عند الإقلاع** لا عند كل طلب: الصفحات تُبنى في المسار
// الساخن، وفحصُ القرص لكل وسم شيفرة في كل طلب ثمنٌ لا داعي له.
import { statSync } from 'node:fs';
import { resolve } from 'node:path';

const ROOT = new URL('../..', import.meta.url).pathname;
const PUBLIC = resolve(ROOT, 'src/web/public');
const stamps = new Map();

// يقبل «/static/pages/opps.js» ويعيده موسوماً. وأي عنوان لا يبدأ بـ`/static/` — أو ملفٍّ
// غير موجود — يُعاد كما هو: الوسم تحسينٌ لا شرطٌ لعمل الصفحة، فلا يكسرها غيابُه أبداً.
export function asset(url) {
  if (typeof url !== 'string' || !url.startsWith('/static/')) return url;
  if (url.includes('?')) return url;
  if (!stamps.has(url)) {
    let v = '';
    try {
      const st = statSync(resolve(PUBLIC, url.slice('/static/'.length)));
      v = Math.floor(st.mtimeMs).toString(36);
    } catch { v = ''; }
    stamps.set(url, v);
  }
  const v = stamps.get(url);
  return v ? `${url}?v=${v}` : url;
}
