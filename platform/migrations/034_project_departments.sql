-- مشروعٌ تعمل عليه أكثر من إدارة
--
-- «هذان المشروعان مشتركان بين إدارة البيانات والذكاء الاصطناعي والمدن الذكية — فلازم في
-- المشاريع تطلع، والتسكين يطلع فيها بشكل صحيح، لأنه مشترك بين إدارتين. ولازم المنصة
-- تستقبل هذا الشيء» — بلسان المالك (مشروعا رصد الحافلات، 2026-08-12).
--
-- النظير الحرفي لترحيلة 026 (opportunity_department): الفرصة كسبت جدول مشاركةٍ يومها،
-- وبقي المشروع على عمودٍ واحد — فمن ربح الفرصةَ المشتركة وجد مشروعها محجوباً عن الإدارة
-- الشريكة، وتسكينُ موظفيها عليه يظهر لمديرهم بنداً مطويّ الاسم. الجدول يقول «من يعمل
-- على المشروع ويراه في قوائمه»، لا من يُحسب عليه.
--
-- والعمود الأصلي (project.department_id) يبقى وهو «الإدارة المسؤولة»: النسبة المالية
-- وجمعُ آخر السنة عليها وحدها — ولو جُمع على كل مشارِكٍ لحُسب المشروع الواحد مرتين.
--
-- ولا يُكرَّر الزوج: المفتاح الأساسي مركّب، فإضافة إدارةٍ مرتين لا تُنشئ صفّين.
CREATE TABLE IF NOT EXISTS project_department (
  project_id    TEXT NOT NULL REFERENCES project(id),
  department_id TEXT NOT NULL REFERENCES department(id),
  created_at    TEXT NOT NULL,
  created_by    TEXT REFERENCES app_user(id),
  PRIMARY KEY (project_id, department_id)
);

-- الفهرس على الإدارة: سؤال «ما المشاريع التي تعمل عليها هذه الإدارة» هو ما تفتح به كل
-- إدارةٍ شاشتها، والمفتاح المركّب يبدأ بالمشروع فلا يخدم هذا الاتجاه.
CREATE INDEX IF NOT EXISTS ix_prjdept_dept ON project_department(department_id);
