-- حالُ بريد الاعتمادات لكل معتمِد — صفٌّ واحد هو قفلُ الإرسال وذاكرتُه
--
-- «ممكن اضافه ميزه يترسل التنبيه على الايميل … مو سبام … ويذكّر المستخدم مرة باليوم» —
-- بلسان المالك. فالرسائل مجمَّعة دوماً (رسالةٌ واحدة تسرد كل المعلَّق)، بينها ثلاثون دقيقة
-- على الأقل، وتمتد إلى أربع ساعات حين يعلم صاحبُها بركامٍ يفوق ثلاثة، ولا شيء خارج ساعات
-- العمل (٨–١٨ بتوقيت الرياض)، وتذكيرٌ صباحيٌّ واحد ما دام شيءٌ معلَّقاً.
--
-- ── لماذا جدولٌ لا ذاكرةُ عمليّة ─────────────────────────────────────────────
-- القرار «هل أُرسل الآن» يحتاج «متى أُرسل آخرَ مرة» — وذاكرةُ العملية تُمحى بكل إقلاع،
-- والخادم قد يعمل بأكثر من نسخة. فالصفُّ هنا هو الحَكَم: من ظفر بتحديثه المشروط
-- (`ON CONFLICT … WHERE`) أرسل، ومن خسره سكت — فلا رسالة تتكرر ولو تزامنت النسخ.
--
-- ── ولماذا صفٌّ بالشخص لا بالطلب ─────────────────────────────────────────────
-- قاعدةُ المالك بالمستقبِل لا بالبند: التجميع والتهدئة والتذكير كلها صفاتُ «متى آخرُ
-- رسالةٍ لهذا الشخص»، لا صفات طلبٍ بعينه. ومحتوى الرسالة في طابور البريد لا هنا.
CREATE TABLE IF NOT EXISTS approval_mail_state (
  user_id            TEXT PRIMARY KEY REFERENCES app_user(id),
  last_sent_at       TEXT,              -- لحظة آخر رسالة قُيِّدت لهذا الشخص (جديد أو تذكير)
  last_reminder_date TEXT,              -- يومُ الرياض لآخر رسالةٍ حُسبت تذكيرَ ذلك اليوم
  notified_count     INTEGER NOT NULL DEFAULT 0, -- كم بنداً حملته آخر رسالة — للمراقبة لا للقرار
  updated_at         TEXT NOT NULL
);
