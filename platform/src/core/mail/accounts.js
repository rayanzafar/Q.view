// ── قائمة المستقبِلين تتحدّث بنفسها ─────────────────────────────────────────
//
// «كيف ممكن يكون في طريقة يتحدّث دائماً وكذا — لأن حسين الجفري طلب وما وصله كمان» — المالك.
//
// ── لماذا كانت تحتاج يداً في كل مرة ─────────────────────────────────────────
// حارس المستقبِلين يقرأ **قائمةً مكتوبةً بخط اليد** في متغيّر بيئة. وهي تُقرأ مرةً واحدة عند
// إقلاع الخادم. فكل حسابٍ جديد يُنشأ من شاشة الهوية يبقى محجوباً حتى يتذكّر أحدٌ أن يكتب عنوانه
// هناك **ويعيد تشغيل الخدمة**. أي أن إنشاء الحساب — وهو فعلٌ داخل المنتج — لا يكتمل إلا بفعلٍ
// خارجه. ومن نسي، اكتشف النسيان بموظفٍ يطلب رمزاً فلا يصله ولا يعرف لماذا. وقع ذلك ثلاث مرات.
//
// ── والقاعدة الصحيحة كانت أمامنا ────────────────────────────────────────────
// الحارس بُني ليمنع شيئاً محدَّداً: رسائل التقارير التي تخرج إلى **عناوين مستوردة من بيانات
// المنصة القديمة** — جهات وموظفين سابقين لا حسابات لهم هنا. أما **حسابٌ في المنصة** فهو عنوانٌ
// أدخله مديرُ النظام بيده ليُستعمل، وأولُ ما يلزمه رمزُ دخول. فمنعُه ليس حمايةً بل تعطيلٌ للغرض
// الذي أُنشئ له. فالسماح يُشتقّ من سجلّ الحسابات نفسه، ولا يُكتب مرتين.
//
// والقائمة اليدوية تبقى عاملةً فوقه لا بدلاً منه: فيها ما ليس حساباً (بريد المالك الشخصي مثلاً).
//
// ── والحدّ يبقى محفوظاً من ثلاثة أطراف ──────────────────────────────────────
//  · الحساب **المُغلق عليه عمداً** (`deactivated_at`) لا يُسمح له — تعطيلٌ يترك بريده مفتوحاً
//    ليس تعطيلاً.
//  · الحساب المحذوف ناعماً لا يُقرأ أصلاً.
//  · ومفتاحٌ يُعيد الحارس الصارم القديم (`SANAD_MAIL_ACCOUNTS_ALLOWED=0`) لمن أراد قائمةً
//    مغلقةً باليد وحدها — القرار يبقى بيد المُشغّل، والافتراض هو الذي تغيّر.
import { all } from '../db/index.js';
import { config } from '../config.js';

const norm = (a) => String(a || '').trim().toLowerCase();

// لقطةٌ في الذاكرة تُحدَّث كل دقيقة: استعلامٌ لكل رسالةٍ ترسَل ثقيلٌ بلا داعٍ، ودقيقةٌ تأخيرٍ في
// سريان حسابٍ أُنشئ للتوّ لا يلاحظها أحد — والمهم أن الأمر لا يحتاج إعادة تشغيل بعد اليوم.
const TTL_MS = 60_000;
let snapshot = new Set();
let loadedAt = 0;

export function accountEmails() { return snapshot; }

// تُنادى قبل كل فلترةٍ حقيقية (الإرسال) وقبل تصيير شاشة الهوية. وفشلُ القراءة لا يُسقط الإرسال
// ولا الشاشة: تبقى اللقطة السابقة — والقائمة اليدوية تحت كل حال.
export async function refreshAccountEmails({ force = false } = {}) {
  if (!config.mailAccountsAllowed) { snapshot = new Set(); return snapshot; }
  if (!force && Date.now() - loadedAt < TTL_MS) return snapshot;
  try {
    const rows = await all(
      `SELECT email FROM app_user
        WHERE deleted_at IS NULL AND deactivated_at IS NULL AND email IS NOT NULL AND email <> ''`);
    snapshot = new Set(rows.map((r) => norm(r.email)).filter(Boolean));
    loadedAt = Date.now();
  } catch { /* تبقى اللقطة السابقة — ولا تُفتح ولا تُغلق بسبب خطأ قراءة */ }
  return snapshot;
}

// للاختبارات وللإقلاع: تفريغُ اللقطة يجبر القراءة التالية على الذهاب إلى القاعدة.
export function resetAccountEmails() { snapshot = new Set(); loadedAt = 0; }
