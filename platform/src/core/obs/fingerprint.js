// بصمةُ العطب — تعريفُ «هذا هو العطب نفسه».
//
// والتجميع الخاطئ أسوأ من غيابه: مجموعةٌ تخفي عطبَين مختلفَين تُقرأ مرةً ثم تُهمَل. فالقاعدة
// هنا خشونةٌ مقصودة — يُجمَع ما نثق أنه واحد، ويُترك ما نشكّ فيه منفصلاً — ويبقى نصُّ العطب
// وأثرُه محفوظَين على الصف كي يرى الإنسانُ بعينه إن كانت المجموعة تضمّ شيئين.
//
// وثلاثة مزالق واقعية في هذا المستودع بالذات:
//  ① **رقم السطر**: لو دخل البصمة لصار كلُّ نشرٍ يمسّ الملف يُنشئ «عطباً جديداً» للعلّة
//    نفسها — فيتعوّد القارئ أن التنبيه كاذب. يُسقَط، ويبقى الملفُّ والدالة.
//  ② **قيمٌ محقونة في نصٍّ عربي**: «تقرير غير معروف: <مفتاح>» ومفتاحُه من المسار — أي أن
//    أيَّ داخلٍ يستطيع توليد مجموعاتٍ بلا حدّ. تُجرَّد القيم، ويبقى فوق ذلك سقفٌ عام.
//  ③ **مسار الجذر**: أثرٌ من الحاوية وآخرُ من جهاز التطوير للعطب نفسه يجب أن يتطابقا.
import { createHash } from 'node:crypto';

// علاماتُ الاتجاه لا تُرى ولا يُزيلها trim، ونصُّنا عربيٌّ يأتي من مصادر شتّى (استيراد
// إكسل، كتابةٌ بيد) — فنصّان متطابقان بالعين يُنتجان بصمتَين ما لم يُطبَّعا.
const INVISIBLE = /[​-‏‪-‮⁦-⁩﻿]/g;
const AR_DIGITS = /[٠-٩۰-۹]/g;

// تجريدُ القيم من النص. `\p{N}` لا `\d`: الأرقام العربية-الهندية أرقامٌ أيضاً.
export function normMessage(msg) {
  return String(msg == null ? '' : msg)
    .normalize('NFC').replace(INVISIBLE, '').replace(AR_DIGITS, '0')
    .replace(/[a-z]{2,4}_[A-Za-z0-9_-]{6,}/g, '#')
    .replace(/[\w.+-]+@[\w.-]+\.\p{L}{2,}/gu, '#')
    .replace(/https?:\/\/\S+/g, '#')
    .replace(/\d{4}-\d{2}-\d{2}[T\s][\d:.]+Z?/g, '#')
    .replace(/\b[0-9a-f]{8,}\b/gi, '#')
    .replace(/[«"'`(\[]([^»"'`)\]]{0,80})[»"'`)\]]/gu, '#')
    .replace(/\p{N}+/gu, '#')
    // قيمةٌ مُذيَّلة بعد نقطتين بلا علامات اقتباس — وهو شكلُ «تقرير غير معروف: <مفتاح>»
    // حيث المفتاح من العنوان. يُجمَع عمداً: أن تندمج رسالتان تختلفان بقيمةٍ مذيَّلة أهونُ
    // من أن يفتح داخلٌ واحد ألفَ مجموعة. والنصُّ الكامل محفوظٌ على الصف لمن أراد التفريق.
    .replace(/:\s*\S{1,80}$/u, ': #')
    .replace(/\s+/g, ' ').trim().slice(0, 160);
}

// أول إطارٍ من شيفرة المنتَج — بلا رقم سطر، وبلا مسار جذر.
export function topAppFrame(stack) {
  for (const raw of String(stack || '').split('\n')) {
    if (!/\bat\b/.test(raw)) continue;
    const line = raw.replaceAll(process.cwd() + '/', '').replaceAll('/app/', '');
    // إطارات المُشغّل والحِزم تتغيّر مع ترقيته — لو دخلت البصمة لأعادت ترقيةٌ بصمَ كل شيء.
    if (/node:internal|node_modules/.test(line)) continue;
    const m = line.match(/at\s+(?:async\s+)?([^\s(]+)?\s*\(?([^\s():]*src\/[^\s():]+)/);
    if (m) {
      const fn = (m[1] || '').replace(/^.*\./, '').slice(0, 60);
      return `${m[2]}${fn ? '#' + fn : ''}`;
    }
  }
  return '';
}

/**
 * البصمة. `parts` = { kind, errKind, source, message, stack }.
 * وستّ عشرة خانة ست عشرية عمداً: أبجديّةُ الست عشرة **لا تستطيع** تهجئة كلمةٍ محظورة في
 * واجهة المستخدم، والرمز القصير هو المعرّف الوحيد الذي يُعرض لإنسان — فالسلامة بالبناء
 * لا بالحظّ. (معرّفٌ بترميزٍ آخر قد يحوي يوماً كلمةً محظورة فيُحمّر مسحَ نشرٍ بلا سبب.)
 */
export function fingerprint({ kind, errKind, source, message, stack }) {
  const frame = topAppFrame(stack) || 'unknown';
  const key = [kind || 'http', errKind || 'Error', source || '', normMessage(message), frame].join('|');
  return createHash('sha256').update(key).digest('hex').slice(0, 16);
}

// الرمز القصير المعروض. ست عشريٌّ دائماً ⇒ آمنٌ أمام ماسح التسريبات بالبناء.
export const shortCode = (fp) => String(fp || '').slice(0, 8);
