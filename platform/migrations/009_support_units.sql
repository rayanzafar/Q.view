-- 009: نوع الوحدة التنظيمية — تمييز «قطاع تسليم» عن «وحدة مساندة» داخل الجدول نفسه.
--
-- المشكلة التي يغلقها هذا الملف: المالك حاسم في أن قطاعات التسليم **أربعة** لا خامس لها (الحلول،
-- الاستشارات، المشاريع الاستراتيجية، SAP)، وفي الوقت نفسه وصف وحدات قائمة فعلاً لا تتبع أي قطاع
-- منها: «الخدمات المشتركة» و«تطوير الأعمال» و«المالية» — إدارات مساندة على مستوى الشركة، فيها
-- موظفون حقيقيون يُستعان بهم على مشاريع القطاعات وفرصها. اليوم لا مكان لهؤلاء في المخطط: من
-- يُسجَّل تحت قطاع يظهر خامساً في كل مقارنة مبيعات، ومن يبقى بلا قطاع يختفي من الشجرة ومن كل
-- كشف. العمود أدناه يفصل الغرضين بلا تفريخ جدول ثانٍ: القطاع يحمل أهدافاً وإيراداً، والوحدة
-- المساندة تحمل أشخاصاً وكلفة.
--
-- هذا هو نموذج «الوحدة الإشرافية + نوع الوحدة» المعمول به في أنظمة الموارد البشرية الكبرى
-- (Workday وSuccessFactors): شجرة واحدة للوحدات كلها، وخانة نوع تقول ماذا تعني كل وحدة.
--
-- ما استُبعد من هذه الترحيلة عمداً (لئلا يُعاد إدخاله بلا قرار):
--   • **جعل department.sector_id يقبل الفراغ**: كان البديل المطروح ليعيش موظفو المساندة بلا قطاع.
--     مرفوض لسببين: العمود معرَّف NOT NULL في 001، وإزالة الإلزام جملتان مختلفتان بين المحرّكين
--     (Postgres تعدّل العمود في مكانه، وSQLite تتطلب إعادة بناء الجدول كاملاً) بينما migrate.js
--     يعيد كتابة **الأنواع** فقط لا صيغ الجُمل — فالنتيجة ترحيلة تعمل على محرّك وتنكسر على الآخر.
--     ولأن الفراغ في عمود إلزامي يُنتج صفوفاً يتيمة لا تظهر في أي شجرة، وهو عين الخلل المُراد سدّه.
--   • **إنشاء وحدات المساندة نفسها هنا**: إنشاء «الخدمات المشتركة» أو «تطوير الأعمال» قرار تشغيلي
--     يتخذه المسؤول من الشاشة فيمرّ بخدمة القطاعات وبتدقيقها الكامل (من أنشأ ومتى). ترحيلة تدسّ
--     صفوفاً تنظيمية بصمت تُنتج وحدات بلا صاحب ولا سطر تدقيق، ولا أحد يعرف من قرّرها.
--   • **قيد CHECK على القيم المسموحة**: التحقق يقع في طبقة الخدمة برسالة عربية تقول ما الخطأ وما
--     البديل، أما قيد المحرّك فيعطي خطأً خاماً لا يُعرض لمستخدم، ويُجمَّد التعداد في المخطط فلا
--     يُضاف نوع ثالث مستقبلاً إلا بإعادة بناء الجدول على SQLite.
--   • **فهرس على العمود**: عدد الوحدات التنظيمية بالعشرات في أسوأ الأحوال، والمسح الكامل عليها
--     أرخص من فهرس يُصان بلا فائدة.
--
-- توافق كامل مع القائم (backward compatible):
--   • عمود واحد اختياري يُضاف، ولا حذف ولا إعادة تسمية لأي عمود أو فهرس قائم — فكل إدخال قائم
--     لا يذكر العمود يظل يعمل، ولا تنكسر أي شاشة منشورة.
--   • التعبئة الرجعية هنا **حقيقة لا تخمين**: كل صف قائم في الجدول اليوم هو قطاع تسليم فعلي
--     (القطاعات الأربعة) لأن وحدات المساندة لم يكن لها تمثيل أصلاً قبل هذا الملف. لذلك تُملأ
--     القيمة صراحةً بدل تركها فارغة ثم تفسيرها ضمنياً في كل استعلام على حدة.
--
-- قابلية النقل (SQLite + Postgres عبر scripts/migrate.js):
--   • النمط المتّبع في هذا المستودع `ALTER TABLE … ADD COLUMN` مجرّداً (انظر 002 و006 و007 و008).
--     صيغة ADD COLUMN IF NOT EXISTS لا يدعمها SQLite بأي إصدار (تدعمها Postgres وحدها)، وعدم
--     التكرار مضمون أصلاً على مستوى **الملف**: migrate.js يسجّل كل ملف في schema_migration ولا
--     يعيد تطبيقه — فالإدمبوتنسي على مستوى الملف لا على مستوى الجملة.
--   • ADD COLUMN بلا قيمة افتراضية يترك الصفوف القائمة فارغة على المحرّكين معاً، فتأتي جملة
--     التعبئة بعده مباشرة لتضع القيمة الصحيحة، وشرط «فارغ» فيها يجعلها آمنة لو أُعيد تشغيلها.
--   • لا علامة استفهام لاتينية في هذا الملف إطلاقاً — ولا حتى داخل تعليق: طبقة الوصول تستبدل كل
--     واحدة منها بمعامل مربوط قبل تنفيذ الملف على المحرّك الآخر.

-- ─────────────────── نوع الوحدة: قطاع تسليم أم وحدة مساندة ───────────────────
-- delivery ⟵ قطاع تسليم: له أهداف مبيعات وإيراد، ويظهر في مقارنات القطاعات ومحوّل القطاع.
-- support  ⟵ وحدة مساندة على مستوى الشركة: تحمل موظفين وكلفة، بلا أهداف وبلا حصة في المقارنات،
--            وموظفوها مورد مشترك يُسكَّن على مشاريع أي قطاع وفرصه.
ALTER TABLE sector ADD COLUMN kind TEXT;

-- كل وحدة قائمة اليوم هي قطاع تسليم — الجملة تكتب هذه الحقيقة صراحةً في البيانات.
UPDATE sector SET kind = 'delivery' WHERE kind IS NULL;
