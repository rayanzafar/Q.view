-- مهمةُ عملٍ ترتبط بمشروع أو فرصة تنتظر اعتماد مدير صاحبها
--
-- «موضوع الاعتمادات: أي موظف يضيف مهمة لازم المدير يعتمدها عشان تنضاف له — إذا كانت مهمة
--  متعلّقة بالمشروع أو فرصة معيّنة» — بلسان المالك.
--
-- ── لماذا عمودٌ مستقلّ لا قيمةٌ سادسة في «الحالة» ────────────────────────────
-- عمود `task.status` يحمل **سير عمل المهمة** كاملاً (قيد التنفيذ · معطَّلة · قيد المراجعة ·
-- منجزة · ملغاة)، وتقرؤه كل لوحة وكل عدّاد وكل تقرير. وإضافةُ قيمةٍ سادسة إليه تعني أن كل
-- موضعٍ يعدّ المهام صار عليه أن يعرف أنها ليست مهمةً بعد — ومن نسي موضعاً عدّ عملاً لم يُعتمد.
--
-- والانتظارُ ليس حالةَ عملٍ أصلاً بل حالةَ **وجود**: المهمة المعلَّقة ليست «مهمةً في مرحلة»،
-- بل مهمةً لم تُضَف بعد. وهذا بالضبط ما قرّرته المنصة في تأكيد التسكين: «عضويةٌ تنتظر تأكيداً
-- ليست عضويةً بعد». فالعمودان يعملان معاً ولا يتنازعان: `status` يقول أين وصل العمل،
-- و`approval_state` يقول هل صار عملاً أصلاً.
--
-- ── والفراغ هو الأصل ────────────────────────────────────────────────────────
-- كل صفٍّ قائم يبقى فارغاً — أي «لا انتظار»، وهو الحال الأصل. فلا ترحيل صفٍّ واحد، ولا مهمةٌ
-- قائمة تختفي من قائمة صاحبها لحظة تطبيق الترحيلة.
ALTER TABLE task ADD COLUMN approval_state TEXT;

-- سؤال «ما المعلَّق» يُسأل في كل قائمة مهام، فيُقرأ بالفهرس لا بمسح الجدول.
CREATE INDEX IF NOT EXISTS ix_task_approval ON task(approval_state);
