export const emptyCaps = () => Object.fromEntries(CAPABILITY_KEYS.map((k) => [k, false]));

const passes = (item, caps) => {
  if (typeof item === 'string') return true;
  if (item.cap && !caps[item.cap]) return false;
  if (item.not && caps[item.not]) return false;
  return true;
};
const textOf = (item) => (typeof item === 'string' ? item : item.text);
const pick = (items, caps, max) => (items || []).filter((i) => passes(i, caps)).map(textOf).slice(0, max);
const first = (items, caps) => {
  for (const i of items || []) if (passes(i, caps)) return textOf(i);
  return null;
};

