-- ٠١٩ — فصلُ ضريبة القيمة المضافة عن المبلغ: رقمٌ واحد كان يقول شيئين، فصار ثلاثة صريحة.
--
-- العيب: `invoice.amount_halalas` يخزّن ما يدفعه العميل **شاملاً الضريبة**، وكل قارئٍ في المنصة
-- يقرؤه «إيراداً». فتقول الشاشة «المفوتر ١٥٬٥٥٦٬٠٥٢ ر.س.» بينما إيراد الشركة الحقيقي
-- ١٣٬٥٢٧٬٠٠٢ — والفارق ٢٬٠٢٩٬٠٥٠ ليس مالاً للشركة أصلاً، بل ضريبةٌ تُحصَّل نيابةً عن الدولة
-- وتُورَّد إليها. أي أن كل تقرير إيراد وكل هامش وكل جسر مالي كان يقرأ رقماً أعلى من حقيقته
-- بمليونين، ويقارن هذا الرقم المتضخّم بمستهدفاتٍ موضوعة صافيةً أصلاً — فتخرج نسبة تحقّقٍ كاذبة.
--
-- قرار المالك حرفياً: «افصل الضريبة عن المبلغ — ودائماً لازم تعرف المبلغ مع الضريبة كم وبدون كم،
-- لأنه هذا مهم للإيراد في المنصة كلها وفي العقود وكل شيء. عمّم هذه بطريقة مناسبة في أي شيء في
-- المنصة له علاقة.» فالمطلوب قاعدة معمَّمة لا خانةٌ في الفاتورة وحدها.
--
-- ═══ قرار التخزين: الإضافة بجانب العمود لا إعادة توجيهه ═══════════════════════════════════════
-- الخيار الآخر كان أن يصير `amount_halalas` صافياً وتُضاف خانة للضريبة. رُفض ببرهان لا بذوق:
-- العمود يُقرأ اليوم في ملفاتٍ خارج وحدة المالية كلها — صفحة العميل، ولوحة القطاع، ولوحة الرئيس
-- التنفيذي، ومحوّل الاستيراد والتصدير، ومقاييس التقارير، وسكربتات البذر والترحيل. وإعادة توجيهه
-- إلى الصافي تغيّر معنى كل واحد من هؤلاء **صامتةً**: لا خطأ يُرفع، ولا سطر يتغيّر، فقط أرقامٌ
-- تنقص خمسة عشر بالمئة في شاشاتٍ لا يعرف أحدٌ أنها تأثّرت. والأسوأ: التحصيل والمستحق يجب أن
-- يبقيا إجماليَّين (العميل يدفع الإجمالي)، فقلبُ العمود كان يقتضي قلبَ بعض القرّاء دون بعض —
-- وهو بالضبط ما يُنتج رقمين لسؤال واحد.
-- فالقاعدة المعتمدة: `amount_halalas` يبقى على معناه اليوم (الإجمالي، ما يدفعه العميل فعلاً)،
-- ويُضاف بجانبه عمودان: الصافي والضريبة. من يريد الإيراد يقرأ الصافي، ومن يريد المطالبة يقرأ
-- الإجمالي، وكلٌّ يُسمّى باسمه.
--
-- ═══ العمودان يبدآن فارغَين لا أصفاراً ══════════════════════════════════════════════════════
-- لا DEFAULT 0 هنا عمداً. صفرٌ في خانة الضريبة يعني «صفٌّ معفى» وهو خبرٌ محاسبي؛ والفراغ يعني
-- «لم يُسجَّل بعد» وهو خبرٌ آخر. وقاعدة المنتج المعلنة أن الصفر ليس غياباً، فلا يجوز أن يبدأ
-- عمودٌ بقيمة تدّعي إعفاءً لم يقرّره أحد. والصفوف القائمة تُملأ أدناه بالتعبئة الرجعية، أما ما
-- يُكتب لاحقاً من مساراتٍ لا تعرف الضريبة (سكربتات البذر، محوّل الاستيراد) فيصل فارغاً — ولذلك
-- تقرأ الخدمات الصافيَ بصيغة COALESCE على القاعدة نفسها المكتوبة هنا، فلا يسقط صفٌّ من الإيراد
-- لأن كاتبه لم يعرف بالضريبة.
--
-- ═══ التقريب: الصافي يُقرَّب والضريبة تُشتقّ ═════════════════════════════════════════════════
--   الصافي = الإجمالي × ١٠٠ ÷ ١١٥ بالقسمة الصحيحة (تُسقط الكسر)، ثم الضريبة = الإجمالي − الصافي.
-- ولا تُقرَّب الضريبة استقلالاً: لو قُرِّب الطرفان كلٌّ على حدة لخرج مجموعهما مخالفاً للإجمالي
-- بهللةٍ في الصفوف التي لا تقبل القسمة، ولتراكم الفارق عبر آلاف الصفوف حتى يظهر في المطابقة.
-- وبهذا الترتيب يتحقّق «صافٍ + ضريبة = إجمالي» لكل صفٍّ ولكل مجموعٍ بلا هللةٍ ضائعة.
-- والقسمة الصحيحة تتصرّف التصرّف نفسه على المحرّكَين (SQLite وPostgres يقتطعان نحو الصفر)،
-- ونظيرتها في الشيفرة `Math.trunc` في `src/modules/finance/vat.js` — قاعدة واحدة في ثلاثة مواضع.
--
-- ═══ ما دخل النطاق ═══════════════════════════════════════════════════════════════════════════
-- المعيار: هل الرقم مبلغٌ إجمالي في مستندٍ تجاري مع طرفٍ خارجي يحمل ضريبةً فعلاً.
--   • `invoice.amount_halalas`         — الفاتورة والمستخلص: أصل الداء.
--   • `contract.value_halalas`         — قيمة العقد مع العميل شاملة الضريبة.
--   • `contract_payment.amount_halalas`— دفعات العقد، أجزاءٌ من القيمة نفسها.
--   • `revenue_line.amount_halalas`    — بند الإيراد المحقق، وهو الرقم الذي يُقارن بالمستهدف.
--   • `collection.amount_halalas`      — العميل يدفع الإجمالي، ففصلُه لازمٌ لمطابقة التحصيل
--                                        بالفواتير: لولاه لَما أمكن القول كم من المحصَّل إيراد.
--   • `purchase_order.amount_halalas`  — ضريبة المورّد مدخلٌ قابل للاسترداد، فالإجمالي ليس كلفة.
--
-- ═══ ما بقي خارج النطاق ولماذا ═══════════════════════════════════════════════════════════════
--   • `employee.salary_halalas` — الرواتب لا تحمل ضريبة قيمة مضافة أصلاً. لا سؤال هنا.
--   • `budget.target_*` و`sector.target_*` — المستهدفات تُوضع صافيةً أصلاً كما يقرّرها المالك،
--     وفصلُها ثانيةً يخصم خمسة عشر بالمئة من رقمٍ لم يحملها قط. والأثر انقلابٌ في الاتجاه: نسبة
--     التحقّق كانت تُقارن محقَّقاً إجمالياً بمستهدفٍ صافٍ فتتضخّم، ولو قُلبت المستهدفات لانكمشت
--     من الجهة الأخرى. التصحيح أن يصير **المحقَّق** صافياً ويبقى المستهدف كما هو، وهو ما تفعله
--     هذه الترحيلة بتعبئة `revenue_line`.
--   • `opportunity.value_halalas` و`proposal.value_halalas` و`pricing_line.unit_*` — تقديرات ما
--     قبل التعاقد: ليست مستنداً ضريبياً ولم تُصدَر بها فاتورة، وفصلُ ضريبةٍ من رقمٍ تقديري ادّعاءُ
--     دقّةٍ لا وجود لها.
--   • `project.revenue_halalas` و`contract_value_halalas` و`po_value_halalas` — أعمدة لقطة
--     مشتقّة من الجداول أعلاه، وقد أرست ٠١٧ السابقة صراحةً: الاشتقاق يجري وقت القراءة لا يُجمَّد
--     في عمودٍ يشيخ. فتجميد صافٍ ثانٍ بجانب إجمالي مجمَّد يضاعف الخانة الشائخة لا يصلحها.
--
-- ═══ `cost_line` — خارج النطاق بقرارٍ مبرَّر ═════════════════════════════════════════════════
-- بند الكلفة ليس مستنداً تجارياً مع طرفٍ خارجي، بل **اعترافٌ بكلفة** كما يقول تعريفه في المنصة
-- («اعترافٌ بكلفة رواتب أو تعاقد باطني أو غيرها، وليس بالضرورة نقداً خرج»). والاعتراف بالكلفة
-- يُسجَّل صافياً بحكم تعريفه: الضريبة المدخلة قابلة للاسترداد فلا تدخل الكلفة أصلاً. فليس فيه
-- إجماليٌّ يُفصل منه شيء. والأخطر: النوع الأول المذكور في تعريف الجدول نفسه هو «رواتب» — ولا
-- ضريبة على راتب. فتعبئةٌ رجعية بخمسة عشر بالمئة على هذا الجدول كانت ستخترع ضريبةً مستردّة على
-- رواتب الموظفين، وتنقص الكلفة المسجَّلة بمقدارها، فيرتفع الهامش ارتفاعاً كاذباً — أي أنها تُصلح
-- طرف الإيراد وتُفسد طرف الكلفة في المعادلة نفسها. تُترك كما هي، وبفصل الإيراد وحده يستقيم
-- الهامش: إيرادٌ صافٍ مقابل كلفةٍ صافية.
--
-- ═══ `expense` — عمودان بلا تعبئة رجعية ═════════════════════════════════════════════════════
-- المصروف حركةُ صرفٍ حقيقية: ما خرج من الحساب هو الإجمالي، وضريبةُ مورّده مستردّةٌ فعلاً حين
-- يصدر فاتورةً ضريبية — فالسؤال مشروع هنا كما هو مشروع في أمر الشراء، والمنصة يجب أن تستطيع
-- الإجابة عنه. لذلك يأخذ الجدول العمودين.
-- لكن **لا تعبئة رجعية عليه**: الجدول لا يحمل مورّداً ولا رقم فاتورة ضريبية ولا أي قرينة تقول
-- إن هذا الصف حمل ضريبةً أصلاً، وهو يخلط في حقلٍ وصفيٍّ حرٍّ واحد ما لا يقبل خلطاً — مستردّات
-- الموظفين (لا ضريبة عليها) والرسوم الحكومية والتأشيرات (معفاة) بجانب المشتريات الخاضعة. فتعبئةٌ
-- شاملة بخمسة عشر بالمئة هنا ليست استرجاعاً لحقيقةٍ مطموسة كما في ٠١٧، بل اختراعُ ضريبةٍ مستردّة
-- على صفوفٍ لم تحملها — وهو تلفيقٌ يقلّل الكلفة ويرفع الهامش كذباً. القاعدة: الفراغ يعني «غير
-- مُسجَّل»، ويُسجَّل من هنا فصاعداً حين يعرفه من يُدخل المصروف، وتقرأ الشاشات الإجماليَّ ما لم
-- يُسجَّل صافٍ. ولا صيغة COALESCE على المصروف في أي قارئ: افتراض الخمسة عشر بالمئة ممنوع هنا
-- بعينه، بخلاف جداول العميل الستة أعلاه.
--
-- ملاحظتان تنفيذيتان مُلزمتان (نفس قيد ٠١٠ و٠١٣ و٠١٤ و٠١٥ و٠١٦ و٠١٧ و٠١٨):
--   • لا علامة استفهام لاتينية في أي سطر هنا ولا حتى داخل تعليق: الملف كله يمرّ على مُحوِّل
--     العلامات إلى ترقيم دولارات عند التشغيل على Postgres، فأي علامة تُفسد النص.
--   • لا وجود لـADD COLUMN IF NOT EXISTS في SQLite، فالإضافة صريحة بلا شرط، وحمايةُ التكرار
--     تأتي من سجل الترحيلات نفسه (ملف واحد يُطبَّق مرة واحدة).
-- وملاحظة ثالثة على الصياغة: CAST إلى BIGINT لا إلى INTEGER. مُحوِّل الأنواع في scripts/migrate.js
-- يقلب INTEGER إلى BIGINT على Postgres فيستوي الأمران في هذا الملف، لكن الصيغة نفسها تُكتب في
-- شيفرة التشغيل حيث لا مُحوِّل — وهناك يكون CAST إلى INTEGER على Postgres عدداً من أربعة بايتات
-- يفيض عند ضرب مبلغٍ كبير في مئة. وBIGINT مقبول على المحرّكَين (SQLite يقرأ ميل النوع من كلمة
-- INT بداخله)، فتُكتب صيغة واحدة في الموضعين بلا فرع.

-- ── العميل: الفاتورة والعقد ودفعاته وبند الإيراد والتحصيل ──
