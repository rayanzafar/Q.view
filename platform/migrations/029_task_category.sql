-- ── إصلاح بياناتٍ قائمة: عملٌ داخلي سُجِّل «مشروعاً» بلا مشروع ──────────────
--
-- شاشة الإضافة السريعة كانت لا تُرسل نوع العمل حين لا جهة للمهمة، والخدمة تكتب عند غيابه
-- القيمة الافتراضية «مشروع» — فكل مهمة داخلية أُضيفت من الشريط السريع خُزِّنت «مشروعاً»
-- وهي بلا مشروع ولا فرصة. الشاشات لم تنكشف لأن مرشِّح «عمل داخلي» يسأل عن غياب الجهتين لا
-- عن نوع العمل، لكن الكذبة باقية في الصف: من يقرأ العمود مباشرةً — تقريرٌ أو تصديرٌ أو
-- استعلامٌ جديد يثق بالنوع — يقرأ «مشروع» عن عملٍ داخلي.
--
-- التصحيح يستهدف الحالة المستحيلة وحدها: «مشروعٌ» بلا مشروعٍ ولا فرصة. والمجموعتان
-- الأخريان خارج الشرط بطبيعته — المهمة الشخصية نوعُها «شخصية» لا «مشروع» فلا يمسّها،
-- ومهمة المشروع الحقيقية جهتُها قائمة فلا يصيبها الشرط أصلاً.
UPDATE task SET work_kind = 'internal'
 WHERE work_kind = 'project' AND project_id IS NULL AND opportunity_id IS NULL;
