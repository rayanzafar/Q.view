// قراءةُ عنوان خادمٍ من إعدادٍ يكتبه إنسان — ونحن نعرف ما يكتبه الإنسان فعلاً.
//
// وقعت هذه بالضبط: نُسخ عنوان خادم البريد من صفحة المزوّد **مع بادئة الرابط**
// (`https://smtp.…`)، فحاول النظام ترجمة النصّ كله اسمَ خادمٍ وأخفق بعبارةٍ تقنية خام لا
// تقول للمُشغّل ما الخطأ ولا أين. والدرس ليس «نظِّف المدخل» بل **متى** تنظّف:
//
//  • ما له معنى واحد يُصحَّح صامتاً: مسافةٌ زائدة، علاماتُ اتجاهٍ غير مرئية (تلتصق بالنسخ من
//    وثيقةٍ عربية فتُنتج خادماً يبدو مطابقاً بالعين ولا يُترجَم)، نقطةُ جذرٍ أخيرة، أقواسُ
//    عنوانٍ سادس، ورابطٌ لا يحمل إلا الخادم.
//  • وما له معنيان يُرفض ولا يُخمَّن. ورابطٌ بمسار (`https://console.example/email/config`)
//    أخطرُ ما هنا: قصُّه يُنتج `console.example` — وهو **يُترجَم فعلاً** ويقود إلى خادم ويبٍ
//    ينتظر حتى تنقضي المهلة. فنكون قد حوّلنا خطأً فورياً واضحاً إلى انتظارٍ صامتٍ في مسار
//    تسجيل الدخول. الرفضُ أرحم.
import { isIP } from 'node:net';

// علاماتُ الاتجاه والمسافات الصفرية لا يُزيلها trim، وهي أكثر ما يلتصق بالنسخ من نصٍّ عربي.
const INVISIBLE = /[​-‏‪-‮⁦-⁩﻿]/g;
// اسم خادمٍ صالح. الشرطة السفلية مسموحة (بعض المزوّدين يُصدرونها)، والنقطةُ غير لازمة كي
// يبقى `localhost` وأسماء الشبكة الداخلية صالحةً في التطوير والاختبار.
const HOSTNAME = /^(?=.{1,253}$)([a-z0-9_](?:[a-z0-9_-]{0,61}[a-z0-9_])?\.)*[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?$/i;

const bad = (message) => ({ host: null, port: null, error: message });

/**
 * يُرجع { host, port, error }. `error` رسالةٌ عربية جاهزة للعرض، و`null` عند السلامة.
 * `port` غير فارغٍ فقط إذا حمله المدخل نفسه (`smtp.x.com:587`).
 */
export function readHost(raw) {
  const cleaned = String(raw == null ? '' : raw).replace(INVISIBLE, '').trim();
  if (!cleaned) return { host: null, port: null, error: null };   // غير مضبوط ≠ خطأ

  let v = cleaned, port = null;

  // ① رابطٌ كامل — يُفكّ بمحلّل الروابط لا بقصٍّ نصّي: يفصل المنفذ، ويُصحّح حالة الأحرف،
  //    ويضع أقواس العنوان السادس، ويكشف اسم المستخدم وكلمة المرور المخبّأين فيه.
  if (/^[a-z][a-z0-9+.-]*:\/\//i.test(v)) {
    let u;
    try { u = new URL(v); } catch { return bad(`تعذّرت قراءة عنوان الخادم «${cleaned}» — اكتب اسم الخادم وحده بلا بادئة`); }
    if (u.username || u.password) return bad('عنوان الخادم يحمل اسم مستخدم أو كلمة مرور — اكتب اسم الخادم وحده، والاعتماد يُضبط في حقلَيه');
    if (u.pathname && u.pathname !== '/') return bad(`«${cleaned}» رابطُ صفحةٍ لا اسمُ خادم — انسخ اسم خادم البريد من صفحة المزوّد (مثل smtp.example.com)`);
    if (u.search || u.hash) return bad(`«${cleaned}» رابطُ صفحةٍ لا اسمُ خادم — اكتب اسم الخادم وحده`);
    // البروتوكول الآمن يحمل نيّةً لا يقرؤها إلا حقل التشفير — فلا يُبتلع صامتاً.
    if (/^smtps:/i.test(u.protocol)) return bad('اكتب اسم الخادم وحده، واضبط التشفير من حقله لا من بادئة العنوان');
    v = u.hostname;                     // يأتي مُقوَّساً للعنوان السادس
    if (u.port) port = Number(u.port);
  } else if (/[/?#@\s]/.test(v)) {
    // ② بلا بادئة لكنه يشبه الرابط — يُرفض ولا يُقصّ: القصّ هنا تخمينٌ لا تصحيح.
    return bad(`«${cleaned}» ليس اسم خادم — اكتب اسم الخادم وحده (مثل smtp.example.com)`);
  } else {
    // ③ منفذٌ ملحق — يُفصل حين لا يلتبس. ونقطتان فأكثر بلا أقواس = عنوانٌ سادس لا منفذ.
    const braced = v.match(/^\[(.+)\]:(\d+)$/);
    const plain = v.match(/^([^:]+):(\d+)$/);
    if (braced) { v = braced[1]; port = Number(braced[2]); }
    else if (plain) { v = plain[1]; port = Number(plain[2]); }
  }

  // ④ أقواس العنوان السادس تُزال: net.connect يريد العنوان عارياً.
  if (/^\[.+\]$/.test(v)) v = v.slice(1, -1);
  // ⑤ نقطةُ الجذر الأخيرة صحيحةٌ في الترجمة لكنها تُفسد اسمَ الخادم في مصافحة التشفير.
  if (v.length > 1 && v.endsWith('.')) v = v.slice(0, -1);

  if (!v) return bad(`تعذّرت قراءة عنوان الخادم من «${cleaned}»`);
  if (port != null && !(Number.isInteger(port) && port >= 1 && port <= 65535)) {
    return bad(`رقم المنفذ في «${cleaned}» خارج المدى المقبول`);
  }
  if (!isIP(v) && !HOSTNAME.test(v)) {
    return bad(`«${cleaned}» ليس اسم خادم صالح — اكتب اسم الخادم وحده (مثل smtp.example.com)`);
  }
  return { host: isIP(v) ? v : v.toLowerCase(), port, error: null };
}

// قيمةٌ منطقية من إعدادٍ نصّي. و«الفارغ» غير مضبوطٍ لا صحيح: مُشغّلٌ مسح الحقل في اللوحة
// لم يطلب تشفيراً ضمنياً — وكان الفراغ يُقرأ `true` فيُحاوَل التشفير على منفذٍ لا يقبله،
// فتنقضي المهلة بعطبٍ يبدو شبكياً وهو إعداد.
export function readFlag(raw) {
  const v = String(raw == null ? '' : raw).replace(INVISIBLE, '').trim().toLowerCase();
  if (!v) return null;
  if (['1', 'true', 'yes', 'on'].includes(v)) return true;
  if (['0', 'false', 'no', 'off'].includes(v)) return false;
  return null;
}

// نصٌّ مُعتمَد يُنسخ ويُلصق (اسم مستخدم طويل، عنوان مُرسِل) — تُزال حوافّه وغير المرئي منه.
export const readText = (raw) => {
  const v = String(raw == null ? '' : raw).replace(INVISIBLE, '').trim();
  return v || null;
};
