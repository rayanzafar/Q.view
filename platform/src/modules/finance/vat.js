// ── قاعدة ضريبة القيمة المضافة: موضع واحد تُكتب فيه، ولا نسخة ثانية ─────────────────────────
// المبلغ المسجَّل في المستندات التجارية (فاتورة، عقد، دفعة، بند إيراد، تحصيل، أمر شراء) **إجمالي**
// أي شاملٌ الضريبة، لأنه ما يدفعه العميل فعلاً. والشركة لا تعترف بهذا الرقم إيراداً: الفارق
// يُحصَّل نيابةً عن الدولة ويُورَّد إليها. فلكل مبلغٍ ثلاثة وجوه لا وجهان:
//   • الإجمالي — ما يُطالَب به ويُدفع ويُحصَّل.
//   • الصافي   — ما تعترف به الشركة إيراداً، وما يُقارن بالمستهدفات (وهي صافية أصلاً).
//   • الضريبة  — الفارق، وهو أمانةٌ لا دخل.
//
// ── التقريب ──────────────────────────────────────────────────────────────────────────────────
// الصافي يُقرَّب والضريبة تُشتقّ من الفارق، لا العكس ولا كلاهما:
//     الصافي = ⌊ الإجمالي × ١٠٠ ÷ ١١٥ ⌋   ثم   الضريبة = الإجمالي − الصافي
// لو قُرِّب الطرفان كلٌّ على حدة لاختلف مجموعهما عن الإجمالي بهللةٍ في كل صفٍّ لا يقبل القسمة،
// ولتراكم الفارق عبر آلاف الصفوف. وبهذا الترتيب يتحقّق «صافٍ + ضريبة = إجمالي» لكل صفٍّ ولكل
// مجموعٍ مهما كان عدد الصفوف — وهو ما يجعل المطابقة بين الفواتير والتحصيل ممكنة أصلاً.
//
// والقسمة هنا **صحيحة** في المواضع الثلاثة كلها بالتصرّف نفسه: `Math.trunc` في الشيفرة، والقسمة
// الصحيحة في SQL على SQLite وPostgres معاً (كلاهما يقتطع نحو الصفر). فلا يختلف رقمٌ باختلاف
// الطريق الذي وصل منه.
//
// ── الحساب بالأعداد الصحيحة ─────────────────────────────────────────────────────────────────
// البسط `gross * 100` عددٌ صحيح مضبوط تماماً في الفاصلة العائمة ما دام دون ٢^٥٣ (وهو ما يعادل
// تسعين ألف مليار ريال)، وناتج القسمة إما عددٌ صحيح مضبوط وإما يبعد عن أقرب عددٍ صحيح بما لا
// يقلّ عن ١÷١١٥ — أي أكبر بمراتب من أي خطأ تقريبٍ ممكن. فالاقتطاع مأمون بلا حيلة إضافية.
export const VAT_RATE_PCT = 15;
const SCALE = 100 + VAT_RATE_PCT; // ١١٥ — المقام الذي يردّ الإجمالي إلى الصافي

const H = (v) => Math.trunc(Number(v) || 0);

/** الصافي من الإجمالي (هللات صحيحة). */
export const netOfGross = (gross) => Math.trunc((H(gross) * 100) / SCALE);

/** الضريبة من الإجمالي — دائماً الفارق، فلا هللة تضيع ولا تُخلق. */
export const vatOfGross = (gross) => H(gross) - netOfGross(gross);

/**
 * الإجمالي من الصافي — للإدخال وحده، لا للتخزين بصيغةٍ ثانية.
 *
 * «وينضاف مبلغها مع الضريبة أو بدون» — بلسان المالك. والجهة تقتبس أحياناً صافياً وأحياناً
 * إجمالياً، فإجبارُ المُدخِل على الحساب بنفسه يُنتج أخطاءً صامتة في رقمٍ يُحاسَب عليه.
 *
 * والمخزَّن يبقى **إجمالياً دائماً** كما تقول القاعدة أعلاه: هذه الدالة تحوّل ما كُتب قبل
 * الحفظ، فلا يتغيّر شيءٌ فيما بعده — ولا يصير للمبلغ تفسيران حسب باب دخوله.
 *
 * والتقريب هنا `round` لا `trunc`: الاتجاه معاكس (نضيف الضريبة لا نستخرجها)، والاقتطاع يُنقص
 * هللةً من الإجمالي فيقرأ المُدخِل رقماً أقلّ ممّا كتب. والعودة قد تُنقص هللةً واحدة في المبالغ
 * التي لا تقبل القسمة — وهو أصغر فارقٍ ممكن بالأعداد الصحيحة، ولا يتراكم لأن المخزَّن واحد.
 */
export const grossOfNet = (net) => Math.round((H(net) * SCALE) / 100);

/** الثلاثة معاً — الشكل الذي تعيده الخدمات لكل مبلغ يحمل ضريبة. */
export function splitGross(gross) {
  const g = H(gross);
  const net = netOfGross(g);
  return { gross_halalas: g, net_halalas: net, vat_halalas: g - net };
}

// ── الصيغ في SQL ────────────────────────────────────────────────────────────────────────────
// لماذا COALESCE وليس قراءةَ العمود المخزَّن مباشرةً: العمودان يُملآن بالترحيلة ٠١٩ لكل صفٍّ
// قائم، وتملؤهما خدماتُ المالية لكل صفٍّ جديد — غير أن جداول العميل يكتب فيها أيضاً ما لا يعرف
// بالضريبة: سكربتات البذر والترحيل من النظام القديم ومحوّل الاستيراد. فصفٌّ يصل من هناك بصافٍ
// فارغ كان سيُقرأ صفراً في مجموع الإيراد ويُسقط نفسه بصمت. فالقاعدة المعلنة: **المخزَّن إن وُجد،
// وإلا فالقاعدة القياسية** — وبهذا يستطيع صفٌّ معفى أن يُسجَّل صراحةً (صافٍ = إجمالي وضريبة = صفر)
// ويُحترَم، ولا يُفترض الإعفاء على من لم يقرّره أحد.
//
// و`expense` مستثنى من هذه الصيغة بعينه (انظر تبرير الترحيلة ٠١٩): جدول المصروفات يخلط ما يحمل
// ضريبةً بما لا يحملها، فافتراض الخمسة عشر بالمئة عليه اختراعٌ لا اشتقاق. يُقرأ مخزَّنه إن سُجِّل،
// ويبقى الإجمالي هو الكلفة إن لم يُسجَّل.
//
// وCAST إلى BIGINT لا INTEGER: على Postgres تكون INTEGER أربعة بايتات فيفيض حاصلُ ضرب مبلغٍ
// كبير في مئة؛ وBIGINT مقبولة على المحرّكَين (SQLite يقرأ ميل النوع من كلمة INT بداخلها).

/** صيغة الصافي: المخزَّن إن وُجد، وإلا اشتقاقٌ بالقاعدة القياسية. */
export const netSql = (grossCol, netCol) =>
  `COALESCE(${netCol}, CAST(COALESCE(${grossCol}, 0) AS BIGINT) * 100 / ${SCALE})`;

/** صيغة الضريبة: دائماً الفارق عن الصافي المقروء بالصيغة أعلاه — فيبقى الجمع مغلقاً. */
export const vatSql = (grossCol, netCol) =>
  `(COALESCE(${grossCol}, 0) - ${netSql(grossCol, netCol)})`;

// أسماء الأعمدة كما أرستها ٠١٩: كلها `net_amount_halalas` إلا العقد فقيمته `value_halalas`
// فصافيها `net_value_halalas`. تُجمَّع هنا كي لا يتذكّرها كل مستدعٍ على حدة.
export const NET_OF = {
  invoice: 'net_amount_halalas',
  contract: 'net_value_halalas',
  contract_payment: 'net_amount_halalas',
  revenue_line: 'net_amount_halalas',
  collection: 'net_amount_halalas',
  purchase_order: 'net_amount_halalas',
};

/** مجموع الصافي لجدولٍ من الجداول أعلاه — `netSum('i.amount_halalas', 'i.net_amount_halalas')`. */
export const netSum = (grossCol, netCol) => `COALESCE(SUM(${netSql(grossCol, netCol)}), 0)`;
export const vatSum = (grossCol, netCol) => `COALESCE(SUM(${vatSql(grossCol, netCol)}), 0)`;
