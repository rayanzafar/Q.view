// مصطلحات الشاشات المتاحة له وحدها، بلا تكرار وبترتيب ظهورها في رحلته.
export function termsForPages(keys, caps) {
  const seen = new Set();
  const out = [];
  for (const k of keys) {
    for (const t of PAGES[k]?.terms || []) {
      const term = TERMS[t];
      if (!term || seen.has(t) || !passes(term, caps)) continue;
      seen.add(t);
      out.push({ term_ar: term.term_ar, meaning_ar: term.meaning_ar });
    }
  }
  return out;
}

export function guideLimits(caps, max = 5) {
  return LIMIT_RULES.filter((r) => r.when(caps)).map((r) => r.text).slice(0, max);
}

export function guideIntro(roleId) {
  return ROLE_INTRO[roleId] || DEFAULT_INTRO;
}

export function orderPages(roleId, keys) {
  const seq = [...(ROLE_JOURNEY[roleId] || []), ...JOURNEY_ORDER];
  const rank = new Map();
  seq.forEach((k, i) => { if (!rank.has(k)) rank.set(k, i); });
  const at = (k) => (rank.has(k) ? rank.get(k) : seq.length);
  return [...keys].sort((a, b) => at(a) - at(b) || String(a).localeCompare(String(b), 'ar'));
}

export function guideTour(key, caps) {
  const t = TOURS[key];
  if (!t) return null;
  const steps = (t.steps || [])
    .filter((s) => passes(s, caps))
    .map((s) => ({ anchor: s.anchor, title_ar: s.title_ar, body_ar: s.body_ar }));
  if (!steps.length) return null;
  return { page: key, title_ar: t.title_ar, steps };
}
