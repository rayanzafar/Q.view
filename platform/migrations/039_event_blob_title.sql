-- ٠٣٩ — «الفعاليات»: عنوانٌ لصورة الكشك في جدول الصور.
--
-- الترحيلة ٠٣٨ بنت event_blob لصورة البطاقة وحدها: بايتاتٌ مرجعُها البطاقة، ولا تحتاج اسماً
-- لأن البطاقة اسمُها. ثم جاء الكشك (E2): صورُ رموزٍ تُعرض على شاشة الجناح ليمسحها الزائر
-- بجواله — رابط الشركة، نموذج التسجيل، ملف التعريف — وكلُّ صورةٍ منها تحمل عبارةً يقرؤها
-- الزائر تحتها («امسح لتحميل ملف الشركة») لا معرّفاً. فهذا العمود: title، يُملأ لصور الكشك
-- (kind = qr) ويبقى فارغاً لصور البطاقات (kind = card).
--
-- ── لماذا عمودٌ لا جدول ──────────────────────────────────────────────────────────
-- الصورتان بايتاتٌ في القاعدة بالقرار نفسه (الترحيلة ٠٣٣: قرص الحاوية يزول مع كل نشرة)
-- وبالمرجع نفسه (kind, ref_id)، والفرق بينهما عنوانٌ واحد. جدولٌ ثانٍ من أجل عمودٍ واحد
-- يضاعف مسارات الرفع والقراءة والحذف والمحو مع الفعالية بلا معنى.
--
-- ── إن فشل الإقلاع بـ«عمودٌ مكرَّر: title» ──────────────────────────────────────
-- «ADD COLUMN IF NOT EXISTS» تعرفها Postgres ولا تعرفها SQLite فلا تُكتب في المجموعة المحمولة،
-- والعبارة أدناه لا تُعاد بلا ضرر. و scripts/migrate.js ينفّذ الملف وصفَّ تتبّعه في معاملةٍ
-- واحدة (سجلّ schema_migration يضمن التطبيق مرةً واحدة)، فلا يبقى العمود مضافاً والترحيلة غير
-- مسجَّلة إلا إن أُضيف العمود يدوياً من خارج المنصة. العلاج حينها كما في رأس الترحيلة ٠٣٥:
--   INSERT INTO schema_migration (version, applied_at)
--   VALUES ('039_event_blob_title.sql', '<الآن بصيغة ISO>');
--
-- ولا علامة استفهام لاتينية في الملف كله ولا في تعليق: يمرّ على مُحوِّل العلامات إلى ترقيم
-- دولارات عند التشغيل على Postgres، وإن لزمت فالعربية «؟».
ALTER TABLE event_blob ADD COLUMN title TEXT;
