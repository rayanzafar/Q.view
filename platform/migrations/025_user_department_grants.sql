-- صلاحية شخصية على إدارة: «سجى تشوف كل فرص إدارة الابتكار، مو بس المسكَّنة عليها»
--
-- الحاجة بلسان المالك: «صفحة الفريق لازم يكون فيها إدارة كاملة للموظفين وللصلاحيات اللي تكون
-- عندهم… مدير القطاع يقدر يعطي صلاحيات كعينه، ومدير الإدارة يقدر يعطي صلاحيات… ممكن أنا أحطّ
-- على سجى إنها تشوف كل فرص إدارة الابتكار مو بس المسكَّنة عليها، وفي «فرصي» يطلع لها اللي هي
-- شغالة عليه».
--
-- ── لماذا جدولٌ جديد ولا يكفي الدور ──────────────────────────────────────────
-- الصلاحيات اليوم كلها **بالدور**: `role_permission` تُقرأ مرةً عند الإقلاع وتُخزَّن في ذاكرة
-- المحرّك. وتلبيةُ هذا الطلب بالدور تعني واحداً من سيّئين: إمّا ترقية سجى إلى دورٍ أوسع فتنال
-- معه ما لم يُقصَد لها (الكتابة، وأشخاص الإدارة، وشاشات القيادة)، أو اختراع دورٍ لكل حالة —
-- «استشاري يرى الابتكار»، «استشاري يرى الذكاء» — فتتكاثر الأدوار حتى لا يعرف أحد ما يعنيه كلٌّ
-- منها. والصواب أن يبقى الدور وصفاً للوظيفة، ويُكتب **الاستثناء الشخصي** حيث يُقرأ ويُراجَع.
--
-- ── والمنح إضافةٌ لا استبدال ─────────────────────────────────────────────────
-- الصفّ هنا **يوسّع** ما يراه صاحبه ولا يضيّقه أبداً: القراءة تبقى «ما يمنحه دوري **أو** ما
-- مُنحتُه شخصياً». فلا يمكن لهذا الجدول أن يسلب أحداً وصولاً يملكه — وهو قيدٌ مقصود يجعل
-- مراجعته آمنة: أسوأ ما فيه صفٌّ زائد يُحذف، لا صفٌّ ناقص يُعطِّل عمل أحد.
--
-- ── الحدود المكتوبة في الخدمة لا هنا ────────────────────────────────────────
-- الجدول لا يعرف من يحقّ له المنح؛ ذلك في `src/modules/identity/grants.js`: لا يمنح أحدٌ ما لا
-- يملكه، ولا يمنح نفسه، ولا يُمنَح إلا ما هو **موصولٌ فعلاً** بشاشةٍ تقرؤه (قائمة مغلقة). ووضعُ
-- تلك الحدود في الخدمة لا في قيود الجدول مقصود: هي أسئلةٌ عن **القارئ** لا عن الصفّ، ولا يجيبها
-- قيدُ قاعدةٍ إلا بتكرار محرّك الصلاحيات كله داخلها.
--
-- والحذف ناعم: من يُراجع لاحقاً يحتاج أن يعرف أن الصلاحية كانت ومَن رفعها ومتى، لا أن يجد فراغاً.
CREATE TABLE IF NOT EXISTS user_department_grant (
  id             TEXT PRIMARY KEY,
  user_id        TEXT NOT NULL REFERENCES app_user(id),
  resource       TEXT NOT NULL,                    -- 'opportunity' اليوم؛ والقائمة مغلقة في الخدمة
  action         TEXT NOT NULL,                    -- 'read'
  department_id  TEXT NOT NULL REFERENCES department(id),
  note           TEXT,                             -- سبب المنح بخط مانحه
  granted_by     TEXT REFERENCES app_user(id),
  created_at     TEXT NOT NULL,
  revoked_by     TEXT REFERENCES app_user(id),
  deleted_at     TEXT
);

-- الفهرس على القارئ: يُقرأ مع كل طلب (تُحمَّل منح صاحب الجلسة عند بناء سياقه)، فهو أكثر
-- استعلامات هذا الجدول تكراراً بفارقٍ كبير.
CREATE INDEX IF NOT EXISTS ix_udg_user ON user_department_grant(user_id, deleted_at);
-- وفهرس الإدارة لسؤال المراجعة المقابل: «من يرى هذه الإدارة ولا ينتمي إليها».
CREATE INDEX IF NOT EXISTS ix_udg_dept ON user_department_grant(department_id, deleted_at);
