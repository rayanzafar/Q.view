-- ٠١٣ — دورة حياة معاينة المساعد: صلاحية زمنية، وختم تطبيق، وقطاع، ونتيجة القرار.
--
-- لماذا: كانت المعاينة تُحفظ في ذاكرة العملية وحدها (خريطة داخل الوحدة). ومعنى ذلك ثلاثة أشياء
-- سيّئة مجتمعة: أ) كل إعادة تشغيل تمحو المعاينات المعلَّقة فيضغط المستخدم «تأكيد» فيُقال له إن
-- معاينته غير صالحة بلا سبب مفهوم، ب) عاملان اثنان على المنصة يعنيان معاينةً تُنشأ في عملية
-- وتُؤكَّد في أخرى فلا تُوجَد أصلاً، ج) لا يوجد أثر دائم يقول «من أكّد هذا التغيير ومتى» —
-- وعمود `approved_by` موجود في الجدول منذ البداية ولم يُكتب فيه شيء قط.
--
-- والأخطر: بلا صلاحية زمنية تبقى المعاينة قابلة للتطبيق إلى الأبد. معاينة أُنشئت قبل شهر
-- تُطبَّق اليوم على بيانات تغيّرت تماماً — تغييرٌ وافق عليه صاحبه على واقع لم يعد قائماً.
-- `expires_at` يجعل الموافقة مرتبطة بلحظتها، و`applied_at` يجعل التطبيق حدثاً مؤرَّخاً لا راية.
--
-- و`outcome` يسجّل **نتيجة القرار** لا نص الطلب: مقبول أم مرفوض أم منتهٍ. فالسجل يجيب سؤال
-- الحوكمة «ماذا طُلب من المساعد وبمَ أُجيب؟» بلا أن يحتفظ بنص طلبٍ مرفوض — ونص الطلب المرفوض
-- لا يُحفظ عمداً: طلبٌ رُدّ لا يترك أثراً نصياً يُقرأ لاحقاً على صاحبه.
--
-- ملاحظة تنفيذية مُلزمة لهذا الملف (نفس قيد الترحيلة ٠١٠): لا علامة استفهام لاتينية في أي سطر
-- هنا ولا حتى داخل تعليق، لأن الملف كله يمرّ على مُحوِّل العلامات إلى ترقيم دولارات عند التشغيل
-- على Postgres فيُفسد النص. وإن لزمت علامة استفهام في نصٍّ عربي فالعلامة العربية «؟» هي المستعملة.
-- ولا وجود لـADD COLUMN IF NOT EXISTS في SQLite، فالإضافة صريحة بلا شرط، وحمايةُ التكرار من
-- سجل الترحيلات نفسه (ملف واحد يُطبَّق مرة واحدة).

ALTER TABLE ai_activity_log ADD COLUMN expires_at TEXT;
ALTER TABLE ai_activity_log ADD COLUMN applied_at TEXT;
ALTER TABLE ai_activity_log ADD COLUMN sector_id TEXT;
ALTER TABLE ai_activity_log ADD COLUMN outcome TEXT;

-- سجل المستخدم مرتَّباً زمنياً: شاشة «نشاط المساعد» تقرأ بهذا الترتيب دائماً.
CREATE INDEX IF NOT EXISTS ix_ai_log_user_at ON ai_activity_log(user_id, at);
-- المزلاج الذرّي للتأكيد يبحث عن معاينة **غير مطبَّقة وغير منتهية** بمعرّفها: هذان العمودان
-- هما شرط التحديث الشرطي الذي يمنع تطبيق المعاينة الواحدة مرتين.
CREATE INDEX IF NOT EXISTS ix_ai_log_pending ON ai_activity_log(applied, expires_at);
