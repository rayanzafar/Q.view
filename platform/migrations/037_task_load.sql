-- حِمل المهام: نسبةٌ على المهمة، ومَن أغلقها
--
-- الملاحظة كما قالها المالك: «إذا وضعتُ نسبة المهمة ٥٠٪ وأخذت أسبوعاً، فنصفُ طاقتي مشغولٌ
-- بقية الأسبوع حتى تنتهي؛ وستُّ مهامَّ بنِسَب ١٠+١٠+١٠+١٠+١٠+٥٠ تُظهر الشهر كله ١٠٠٪».
-- أي أن للمهمة وزناً من طاقة صاحبها، ومجموعُ أوزان المفتوحة هو حِملُه المعروض.
--
-- ── لماذا عمودٌ جديد ولا يُعاد استعمال `estimate_hours` ────────────────────────
-- `estimate_hours` قائمٌ منذ أول ترحيلة ويُكتب في موضعين ولا **يُقرأ في موضعٍ واحد** في
-- المستودع كله — ولا صفَّ واحدٍ على البيئة الحيّة يحمل قيمة. والساعةُ فوق ذلك بلا مقام:
-- لا نموذجَ أيام عمل في المنصة ولا تقويمَ عطل، فـ«ثماني ساعات» لا تُترجَم إلى نسبةٍ من
-- طاقة أحد. أما النسبة-من-الشخص فتوافق العُرف القائم أصلاً: `allocation.monthly_json`
-- و`employee.capacity_pct` كلاهما يعُدّ الشهر مئةً. ويُترك `estimate_hours` كما هو.
--
-- ── ولماذا لا يُملأ بأثرٍ رجعي ─────────────────────────────────────────────────
-- كلُّ مهمةٍ قائمة تبقى فارغة، ولا تُقرأ صفراً بل «بلا نسبة مقدَّرة» — وهي حقيقةُ اليوم
-- الأول: لم يُقدِّرها أحد بعد. وصفرٌ مخترَع يجعل المُثقَل يقرأ فارغاً، وهو أسوأ من الفراغ
-- المعلَن (نفس مبدأ الترحيلة 021: «الفراغ يقول لم يُحدَّد بعد بصدق»).
--
-- ولا فهرس جديد: كل قراءات المقياس تمرّ بـ`ix_task_assignee(assignee_user_id, status)`.
ALTER TABLE task ADD COLUMN utilization_pct INTEGER;

-- ── ومَن أغلق المهمة ──────────────────────────────────────────────────────────
-- `completed_at` قائمٌ ويُقرأ، لكن «مَن» غائبٌ تماماً: للمهمة كاتبٌ (`created_by`) ومعدِّلٌ
-- (`updated_by`) ومعتمِدٌ (`approved_by`, ترحيلة 030) ولا مُغلِق. وفي عملٍ يمرّ باعتماد
-- تصير «مَن وسمها منجزة» سؤالاً لا جواب له — وهو نصف صفِّ KI-080.
ALTER TABLE task ADD COLUMN completed_by TEXT;
