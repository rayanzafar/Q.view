-- ٠٢٣ — دفتر الملاحظات الشخصي.
--
-- بلسان المالك: «أضيف مكان الواحد يكتب فيه النوت ويكون بشكل جميل، والنوت يكون بناءً على اليوم
-- أو يكون في قائمة يكتب موضوع ويكتب فيه نوت وكذا».
--
-- ── لماذا جدول جديد هنا، ولا جدول جديد للمهمة الشخصية ──────────────────────────────────────
-- المهمة الشخصية لم تحتج بنيةً: جدول المهام يحمل `work_kind` منذ الترحيلة ٠٠١، وقيمةٌ جديدة
-- فيه («شخصية») تكفي — مهمةٌ بلا مشروع ولا فرصة مُسنَدةٌ إلى صاحبها. فتربح كل ما بُني للمهام
-- بلا سطرٍ واحد من البنية.
-- أما الملاحظة فليست مهمةً ولا نشاطاً ولا مستنداً: لا حالة لها ولا موعد ولا صاحبَ عملٍ ترتبط
-- به. وحشرُها في `crm_activity` كان يعني أن يُقرأ دفتر الشخص في سجل نشاط الفرص، وفي
-- `document` أنها رابطٌ إلى ملفٍ خارج المنصة وهي ليست كذلك. فجدولها جدولها.
--
-- ── الشكل: موضوع ونصّ، واليوم عمودٌ فيها لا نموذجٌ ثانٍ ─────────────────────────────────────
-- المالك خيّر بين «ملاحظة لكل يوم» و«قائمة موضوع ونصّ» — واخترنا الثانية لأن الاحتواء في
-- اتجاه واحد: ملاحظةُ اليوم هي ملاحظةٌ موضوعها يومٌ، أما «ملاحظات اجتماع الترسية» فلا يسعها
-- نموذج اليوم إلا بأن تُحشر في تاريخٍ ثم تضيع — لأن الاسترجاع بعد شهرين يكون بالموضوع لا
-- بتذكّر اليوم الذي كُتبت فيه.
-- وحتى لا يخسر الخيار الآخر شيئاً: `note_date` عمودٌ على كل ملاحظة (اليوم افتراضاً)، فالشاشة
-- تعرضها مجمَّعةً بالأيام. نموذجٌ واحد يخدم القراءتين معاً، لا جدولان يتنافسان.
--
-- ── الخصوصية بنيةً لا عادةً ────────────────────────────────────────────────────────────────
-- `user_id` ليس عمود إسنادٍ بل عمود ملكية: كل استعلام على هذا الجدول مقيَّد به، ولا منح ولا
-- دور يفتحه لغير صاحبه — تماماً كحجّة صفحة «صفحتي» في core/policy/pages.js. ولا عمود قطاع
-- هنا عمداً: الملاحظة لا تخصّ قطاعاً فلا تدخل تجميعاً ولا تقريراً ولا لوحةً لأحد.
--
-- ملاحظتان تنفيذيتان مُلزمتان لهذا الملف (نفس قيد الترحيلتين ٠١٠ و٠١٣):
--   • لا علامة استفهام لاتينية في أي سطر هنا ولا حتى داخل تعليق: الملف كله يمرّ على مُحوِّل
--     العلامات إلى ترقيم دولارات عند التشغيل على Postgres، فأي علامة تُفسد النص. وإن لزمت
--     علامة استفهام في نصٍّ عربي فالعلامة العربية «؟» هي المستعملة.
--   • لا وجود لـADD COLUMN IF NOT EXISTS في SQLite، والحمايةُ من التكرار من سجل الترحيلات نفسه.

CREATE TABLE IF NOT EXISTS personal_note (
  id          TEXT PRIMARY KEY,
  user_id     TEXT NOT NULL REFERENCES app_user(id),
  subject     TEXT NOT NULL,
  body        TEXT,
  note_date   TEXT,                        -- اليوم الذي تخصّه الملاحظة بصيغة سنة-شهر-يوم
  pinned      INTEGER NOT NULL DEFAULT 0,  -- مثبَّتة أعلى الدفتر (٠ أو ١)
  created_at  TEXT NOT NULL,
  created_by  TEXT,
  updated_at  TEXT,
  updated_by  TEXT,
  deleted_at  TEXT
);

-- القراءة الوحيدة على هذا الجدول: «دفتر هذا الشخص، غير المحذوف، بترتيب يومه».
-- فهرسٌ واحد يخدمها كاملةً، ولا فهرس بلا استعلامٍ يطلبه.
CREATE INDEX IF NOT EXISTS ix_pnote_owner ON personal_note(user_id, deleted_at, note_date);
