-- تصنيف المهمة: ما نوع هذا العمل — اجتماع، إعداد تقرير، متابعة، عمل إداري
--
-- «اجتماع داخلي · اجتماع مع جهة · إعداد تقرير · متابعة» — أوصافٌ يكتبها الفريق اليوم داخل
-- عنوان المهمة نفسه، فلا تُجمَع ولا تُرشَّح ولا تُقرأ إلا بعين من كتبها. التصنيف خانةٌ
-- مستقلة تُختار من قائمة جاهزة أو تُكتب حرّة، فيصير سؤال «كم اجتماعاً هذا الأسبوع» سؤالاً
-- تجيب عنه القوائم لا الذاكرة.
--
-- ── لماذا عمودٌ مستقلّ لا قيمٌ جديدة في «نوع العمل» ─────────────────────────
-- عمود `work_kind` يحمل **جهة المهمة**: لمن يعود هذا العمل — مشروع، فرصة، عمل داخلي للشركة،
-- أو دفتر صاحبها الشخصي. وعلى هذا المحور تُبنى الرؤية كلها: من يقرأ المهمة، وفي أي لوحة
-- تظهر، وفي أي عدّاد تُحسب. أمّا التصنيف فمحورٌ آخر لا يمسّ الرؤية إطلاقاً: **صفة النشاط**
-- نفسه. والمهمة الواحدة تحمل المحورين معاً — اجتماعٌ داخلي هو «عمل داخلي» جهةً و«اجتماع»
-- صفةً — فحشرُهما في عمود واحد يجعل كل قارئ لنوع العمل مضطراً لمعرفة أيّ القيم جهةٌ وأيّها
-- وصفٌ، ومن نسي التمييز في موضعٍ خلط دفتر الشخص بلوحة الشركة. محوران، عمودان.
--
-- والقيمة نصٌّ مفتوح لا قائمة مغلقة: القائمة الجاهزة تسكن المعجم في الواجهة (مع خيار «أخرى»
-- يكتب فيه المرء ما شاء)، والقاعدة لا تفرض حصراً — فتصنيفٌ جديد غداً لا يحتاج ترحيلة.
-- والفراغ هو الأصل: كل صفٍّ قائم يبقى بلا تصنيف، ولا يُخترع له وصفٌ لم يقله أحد.
