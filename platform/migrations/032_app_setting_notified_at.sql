-- إعداداتٌ تُدار من الشاشة، وختمُ إخطارٍ على الطلب — بريدُ الاعتمادات صار سياسةً لا ثابتاً
--
-- قرار المالك: التذكيرُ الدوري مُطفأٌ افتراضياً ويُدار من شاشة البريد (تشغيلاً وفاصلاً
-- بالساعات)، ورسالةُ الطلب الجديد فوريةٌ بلا تهدئة وبلا نافذة ساعات — والتهدئةُ نفسها
-- رقمٌ يملكه مدير النظام لا الكود.
--
-- ── لماذا جدولُ إعداداتٍ عام لا جدولٌ لكل ميزة ───────────────────────────────
-- صفٌّ لكل مفتاح، والافتراضاتُ في الكود لا في البذر: قاعدةٌ فارغة تعمل بالسلوك الافتراضي
-- بلا صفٍّ واحد، وكلُّ إعدادٍ قادمٍ صفٌّ جديد لا ترحيلةٌ جديدة. والقيمةُ نصٌّ يفسّره قارئه
-- ويقع على افتراضه عند العطب — فلا قيمةٌ معطوبة تكسر الكنسة.
CREATE TABLE IF NOT EXISTS app_setting (
  key        TEXT PRIMARY KEY,
  value      TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  updated_by TEXT
);

-- ── ختمُ الإخطار على الطلب نفسه ──────────────────────────────────────────────
-- عند تهدئةٍ صفرية يسقط حَكَمُ الوقت بين نسخ الخادم (كلتاهما تجتاز شرطَ «مضى ما يكفي»)،
-- فيصير القفلُ عضويةً دقيقة: «صفوفٌ لم تُذكر في رسالةٍ بعد». التحديثُ المشروط على هذا
-- العمود هو الحَكَمُ الجديد — من ظفر به أرسل، ومن خسره سكت. وهو أيضاً أصدق من حساب
-- الأزمنة: صفٌّ لم يُدَّعَ يبقى قابلاً للادّعاء أبداً، فلا يضيع طلبٌ بانحراف ساعة.
ALTER TABLE approval_request ADD COLUMN notified_at TEXT;

-- ── استدراك المكتوب: ما سبق ذكرُه في رسالةٍ يُختم حتى لا يُعاد إخطارُه لحظة النشر ──
-- كلُّ معلَّقٍ أُنشئ قبل آخرِ رسالةٍ لمعتمِده كان مذكوراً فيها (الرسائل تسرد كل المعلَّق)،
-- فيُختم بوقتها. ومن لم يُذكر قط يبقى فارغاً فتلتقطه أول كنسة — كما كان يستحق رسالةً
-- في النظام القديم أيضاً.
--
-- (عمود last_reminder_date في approval_mail_state لم يعد يُقرأ ولا يُكتب بعد هذه الموجة —
--  يبقى في مكانه: الترحيلات لا تُعدَّل.)
UPDATE approval_request
   SET notified_at = (SELECT s.last_sent_at FROM approval_mail_state s
                       WHERE s.user_id = approval_request.assignee_user_id)
 WHERE status = 'PENDING'
   AND assignee_user_id IS NOT NULL
   AND EXISTS (SELECT 1 FROM approval_mail_state s
                WHERE s.user_id = approval_request.assignee_user_id
                  AND s.last_sent_at IS NOT NULL
                  AND s.last_sent_at >= approval_request.created_at);
