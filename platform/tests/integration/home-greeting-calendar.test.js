// ثلاثة مطالب من المالك على الصفحة الأولى:
//   • «للترحيب خلّيه جنب الاسم: صباح الخير ريان، أو مساء الخير» — وكانت الترويسة تقول «يومٌ
//     للبناء» و«يوم الحسم»: عناوينُ لأيام لا تحيةَ لإنسان.
//   • «الحِكم والأمثال… خلّيها حلوة وشاعرية، ولها أصل ديني وثقافي، للتحفيز في العمل».
//   • «في الكالندر خلّيه يمدّني أضغط على يوم محدَّد ويطلع بوب أب يبيّن إيش فيه».
//
// وأهمّ ما يُحرَس في الحِكم أن **لكل كلمةٍ نسبة**: كلمةٌ بلا مصدر قد تُنسَب خطأً فتصير المنصة
// مصدرَ خطأ يتناقله الناس. وأن تكون **واحدةً لكل الناس في اليوم الواحد** — فتصير حديثاً
// بينهم، والعشوائية تجعل كلاً يرى غير ما يرى زميله.
import { test } from 'node:test';
import assert from 'node:assert/strict';

const H = await import('../../src/modules/home/home.js');

test('التحية تتبع ساعة الرياض لا ساعة الخادم', () => {
  // ٠٦:٣٠ بتوقيت الرياض = ٠٣:٣٠ عالمي
  assert.equal(H.greetingFor(new Date('2026-08-03T03:30:00Z')).hi, 'صباح الخير');
  assert.equal(H.greetingFor(new Date('2026-08-03T16:30:00Z')).hi, 'مساء الخير');
  assert.equal(H.riyadhHour(new Date('2026-08-03T21:00:00Z')), 0, 'منتصف ليل الرياض');
});

test('ولا عناوين أيامٍ غريبة في التحية', () => {
  for (let d = 0; d < 7; d++) {
    const g = H.greetingFor(new Date(Date.UTC(2026, 7, 2 + d, 6, 0)));
    assert.ok(['صباح الخير', 'مساء الخير', 'طاب يومك', 'ليلةٌ طيبة'].includes(g.hi),
      `تحيةٌ غير معروفة: ${g.hi}`);
    assert.ok(!/يوم للبناء|يوم الحسم/.test(g.hi));
  }
});

test('ولكل كلمةٍ في القائمة نصٌّ ومصدر — لا كلمة بلا نسبة', () => {
  assert.ok(H.DAILY_WISDOM.length >= 24, 'القائمة أقصر من أن تدور شهراً بلا تكرار');
  for (const w of H.DAILY_WISDOM) {
    assert.ok(typeof w.t === 'string' && w.t.trim().length > 10, `نصٌّ قصير أو فارغ: ${w.t}`);
    assert.ok(typeof w.s === 'string' && w.s.trim(), `كلمة بلا مصدر: ${w.t}`);
    assert.ok(/[؀-ۿ]/.test(w.t) && /[؀-ۿ]/.test(w.s), 'نصٌّ غير عربي');
    assert.ok(!/[A-Za-z]/.test(w.t), 'حرفٌ لاتيني في كلمة اليوم');
  }
});

test('وكلمةُ اليوم واحدةٌ لكل من يفتح المنصة، وتتبدّل مع اليوم', () => {
  const a = H.wisdomFor(new Date('2026-08-03T06:00:00Z'));
  const b = H.wisdomFor(new Date('2026-08-03T20:00:00Z'));   // نفس اليوم بتوقيت الرياض
  assert.deepEqual(a, b, 'اختلفت الكلمة بين ساعتين من اليوم نفسه');
  const c = H.wisdomFor(new Date('2026-08-04T06:00:00Z'));
  assert.notDeepEqual(a, c, 'لم تتبدّل مع اليوم التالي');
  // وتعود نفسَها بعد دورةٍ كاملة — لا عشوائية تُنسي المنصةَ ما عرضته
  const back = H.wisdomFor(new Date(Date.parse('2026-08-03T06:00:00Z') + H.DAILY_WISDOM.length * 86400000));
  assert.deepEqual(a, back);
});
