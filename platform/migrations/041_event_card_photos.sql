-- ٠٤١ — «الفعاليات»: صورةُ البطاقة تصير قائمةَ صور — رفعُ قيد التفرّد لا غير.
--
-- ما حدث في LEAP: البطاقة وجهان — وجهٌ بالعربية ووجهٌ بالإنجليزية — ومعها كُتيّبُ تعريفٍ
-- يُصوَّر بعدها. فصوّر الملتقِط الوجه الأول ثم الثاني، فمحا الثاني الأول وهو لا يدري:
-- الفهرس الفريد `ux_evb_ref` على (kind, ref_id) كان يجعل كل بطاقةٍ صفَّ صورةٍ واحداً،
-- والخدمة كانت تكتب بـ«عند التعارض حدِّث» — فآخر صورةٍ تفوز وما قبلها يزول بلا سؤال.
-- والذي ضاع لا يُستعاد: البايتات محذوفةٌ محواً فعلياً كقرار الترحيلة ٠٣٨.
--
-- ── القرار: القيدُ وحده يُرفَع — لا عمودٌ جديد ولا جدولٌ ثانٍ ────────────────────────────
-- صفٌّ واحدٌ لكل صورة، وكلُّها بالمرجع نفسه (kind = 'card' وref_id = معرّف البطاقة). ولا
-- عمود «is_cover» ولا «sort_order»: الغلافُ أقدمُ الصور، يُحسب في الخدمة عند القراءة
-- (ORDER BY created_at ASC, id ASC LIMIT 1) ولا يُخزَّن. عمودٌ يُخزِّن الغلاف حقيقةٌ ثانية
-- تحتاج من يحرسها عند كل حذفٍ وإضافة — وحساب سطرٍ واحدٍ أرخصُ من صيانة عمودٍ يكذب.
-- وترتيبُ العرض ترتيبُ الالتقاط: أوّلُ ما صُوِّر هو وجه البطاقة، وما بعده ظهرُها وكُتيّبها.
--
-- ── رموز الكشك لا تتأثّر ────────────────────────────────────────────────────────────────
-- صفُّ الرمز (kind = 'qr') مرجعُه نفسُه — ref_id يساوي id — فهو فريدٌ بالمفتاح الأساسي
-- أصلاً، ولا يحتاج فهرساً فريداً ليحرسه. ورفعُ القيد لا يفتح له باباً: سقفُ رموز الجناح
-- في الخدمة (UPLOAD_LIMITS.qrPerEvent) هو حارسُه كما كان.
--
-- ── وما يجب أن يتغيّر في الخدمة مع هذا الملف ───────────────────────────────────────────
-- إدراجُ صورة البطاقة يصير إدراجاً عادياً: عبارةُ «ON CONFLICT (kind, ref_id) DO UPDATE»
-- تُحذف من `attachContactPhoto`. فبوستجريس يشترط فهرساً فريداً مطابقاً لعناصر التعارض،
-- وقد زال — فتبقى العبارةُ خطأَ خادمٍ (42P10) لا حارساً. وسقفُ الصور لكل بطاقة صار في
-- الخدمة (UPLOAD_LIMITS.photosPerCard)، وتكرارُ الصورة نفسها يُكشف ببصمتها لا بالفهرس.
--
-- والفهرسُ البديل غير فريد على (kind, ref_id, created_at): قراءةُ صور البطاقة الواحدة
-- مرتَّبةً بأقدميّتها هي القراءة الغالبة (الغلاف، والقائمة، والعدّاد) فيخدمها كلَّها.
--
-- ملاحظات تنفيذية مُلزمة (قيد الترحيلات ٠٢٣ و٠٣٦ و٠٣٨ و٠٤٠):
--   • لا علامة استفهام لاتينية في أي سطر هنا ولا حتى داخل تعليق: الملف كله يمرّ على مُحوِّل
--     العلامات إلى ترقيم دولارات عند التشغيل على Postgres. وإن لزمت فالعربية «؟».
--   • لا ALTER TABLE إطلاقاً، وكل عبارة تُعاد بلا ضرر (IF EXISTS للإسقاط، وIF NOT EXISTS
--     للإنشاء) — فخّ الترحيلة ٠٣٥.
DROP INDEX IF EXISTS ux_evb_ref;
CREATE INDEX IF NOT EXISTS ix_evb_ref ON event_blob(kind, ref_id, created_at);
