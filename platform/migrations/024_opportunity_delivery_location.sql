-- موقع التسليم على الفرصة
--
-- «في الفرص، إذا كانت مؤهلة أو ليدز، برضو حطّ مكان نكتب فيه موقع تسليمها» — بلسان المالك.
--
-- والحاجة تحته تظهر مبكراً لا متأخراً: موقع التسليم يحكم الترشيح والتسعير والتسكين قبل أن
-- يُكتب عرضٌ واحد — فرصةٌ تُنفَّذ في مدينةٍ أخرى تعني سفراً وإقامةً في الكلفة، وفريقاً يقبل
-- الانتقال في التسكين. ولذلك ذُكرت المرحلتان الأوليان بالاسم: هناك يُتَّخذ قرار «ندخل أو لا».
--
-- **نصٌّ حرّ لا قائمة**: الجواب أحياناً جهةُ استلامٍ («منصة اعتماد»)، وأحياناً مدينةٌ أو موقعُ
-- تنفيذ («الرياض — مقرّ الوزارة»)، وأحياناً «عن بُعد». وقائمةٌ مغلقة تُجبر الناس على اختيار
-- أقرب خطأ، ثم تُقرأ الشريحة الناتجة كأنها حقيقة. والفراغ مقبول: «لم يُحدَّد بعد» جوابٌ صادق
-- في مرحلة الترشيح، فلا قيمة افتراضية تُكتب نيابةً عن أحد.
--
-- ولا فهرس عليه: حقلٌ يُقرأ مع صفّه ولا يُرشَّح به ولا يُجمَع عليه — والفهرس كلفةُ كتابةٍ بلا
-- قارئ. فإن صار مُرشِّحاً يوماً، فترحيلةٌ تُضيفه حينها.
