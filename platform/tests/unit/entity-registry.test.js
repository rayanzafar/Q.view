// مرجع الجهات السعودية — واليقين الذي يحتاج برهاناً.
//
// هذا الملف يحرس **الأخطاء التي وقعت فعلاً** في أول جولة مطابقة، لا أخطاءً متخيَّلة. جولة
// بتشابه الكلمات وحده أنتجت على بيانات حقيقية:
//   • «الأمن العام» ⟵ «الهيئة الوطنية للأمن السيبراني» — وعلى الأولى ٢٧٠ مليون ريال.
//   • «ميناء جدة الإسلامي» ⟵ «جامعة جدة» — لاشتراكهما في كلمة «جدة».
//   • «مجموعة د. سليمان الحبيب الطبية» ⟵ «مجموعة السعودية» — لاشتراكهما في «مجموعة».
//   • «قطاع الحلول — داخلي» ⟵ «مجلس الوزراء» — لتطابق شرطتين على اختصار فارغ «—».
// كلها كانت ستُنفَّذ لو صُنِّفت «مؤكَّدة». فالفحوص أدناه تُثبت أن أياً منها **لا يُصنَّف
// مؤكَّداً**، وأن المؤكَّد الحقيقي يبقى مؤكَّداً.
//
// تحديث بعد قرار المالك: «الأمن العام» صارت جهةً في المرجع (ent_352) — كان غيابها هو سبب
// الترشيح الخاطئ أصلاً. فالفحص لم يعد «لا تصل إلى شيء» بل **تصل إلى نفسها**، ويبقى شرطه
// الأصلي قائماً بالاسم: لا تصل إلى الأمن السيبراني أبداً.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { matchEntity, entityCount, normalizeEntityName } from '../../src/core/org/entity-registry.js';

test('المرجع محمَّل — وبلا مرجع لا مطابقة أصلاً', () => {
  assert.ok(entityCount() > 300, `عدد الجهات أقل مما ينبغي (${entityCount()})`);
});

// ── اليقين ──────────────────────────────────────────────────────────────────
test('الاسم الرسمي حرفاً بحرف: مؤكَّد ولا يُقترح عليه تغيير', () => {
  const m = matchEntity('وزارة الاقتصاد والتخطيط');
  assert.equal(m.confidence, 'مؤكَّد');
  assert.equal(m.exact, true, 'هو الصواب أصلاً — اقتراح تغييره ضجيج');
  assert.equal(m.abbr, 'MEP');
});

test('العلامة التجارية بين قوسين تُنزَع حين تخصّ الجهة نفسها', () => {
  // «موانئ» اختصار الهيئة العامة للموانئ نفسها، فالقوسان زينة لا تمييز.
  const m = matchEntity('الهيئة العامة للموانئ (موانئ)');
  assert.equal(m.confidence, 'مؤكَّد');
  assert.equal(m.official_name, 'الهيئة العامة للموانئ');
  assert.equal(m.exact, false, 'يُقترح توحيده على الاسم الرسمي');
});

test('قوسان بعلامة لا تخصّ الجهة لا يُنزَعان', () => {
  const m = matchEntity('وزارة الاقتصاد والتخطيط (فرع الرياض)');
  assert.notEqual(m?.confidence, 'مؤكَّد',
    '«فرع الرياض» ليست علامة الوزارة — نزعها يساوي فرعاً بالجهة الأم');
});

test('«هدف» تصل إلى صندوق تنمية الموارد البشرية — وهو ما تعجز عنه مقارنة النصوص', () => {
  const m = matchEntity('هدف');
  assert.equal(m.confidence, 'مؤكَّد');
  assert.equal(m.official_name, 'صندوق تنمية الموارد البشرية');
  assert.equal(m.abbr, 'HRDF');
});

test('اختلاف الهمزة وحده لا يصنع جهةً ثانية', () => {
  const m = matchEntity('الجامعة السعودية الالكترونية');
  assert.equal(m.confidence, 'مؤكَّد');
  assert.equal(m.official_name, 'الجامعة السعودية الإلكترونية');
  assert.equal(normalizeEntityName('الالكترونية'), normalizeEntityName('الإلكترونية'));
});

// ── الأخطاء التي وقعت فعلاً ─────────────────────────────────────────────────
// حارس دائم بالاسم. الخطأ لم يُنفَّذ لأنه أُمسك قبل التنفيذ، ولو نُفِّذ لحمل سجلُّ عميلٍ عليه
// ٢٧٠ مليون ريال اسمَ جهة أخرى. يبقى الفحص قائماً مهما تغيّر المرجع أو خوارزمية المطابقة.
test('«الأمن العام» لا تُطابَق بالأمن السيبراني — الخطأ الذي كان سيمسّ ٢٧٠ مليوناً', () => {
  const m = matchEntity('الأمن العام');
  assert.notEqual(m?.official_name, 'الهيئة الوطنية للأمن السيبراني',
    'مطابقة على كلمة «الأمن» وحدها — وعلى هذا السطر ٢٧٠ مليون ريال');
  // وبعد أن أضافها المالك جهةً قائمة بذاتها (ent_352) صارت تصل إلى **نفسها** يقيناً، بدل أن
  // تبقى بلا مقابل في المرجع فتلتقطها أقرب جهة فيها كلمة «الأمن».
  assert.equal(m?.official_name, 'الأمن العام', 'الجهة مضافة إلى المرجع بقرار المالك');
  assert.equal(m.confidence, 'مؤكَّد');
  assert.equal(m.exact, true, 'الاسم كما يُكتب في التعاملات — لا يُقترح توسيعه إلى «المديرية العامة للأمن العام»');
});

test('الأمن السيبراني يبقى لنفسه، والاسم الموسَّع للأمن العام لا يصنع سجلاً ثانياً', () => {
  const cyber = matchEntity('الهيئة الوطنية للأمن السيبراني');
  assert.equal(cyber.official_name, 'الهيئة الوطنية للأمن السيبراني');
  assert.equal(cyber.abbr, 'NCA');
  assert.equal(matchEntity('الأمن السيبراني').official_name, 'الهيئة الوطنية للأمن السيبراني');
  const long = matchEntity('المديرية العامة للأمن العام');
  assert.ok(long, 'من يكتب الاسم الموسَّع يصل إلى الجهة نفسها');
  assert.equal(long.entity.id, matchEntity('الأمن العام').entity.id, 'سجل واحد لا سجلان');
  assert.equal(long.official_name, 'الأمن العام', 'الاسم الرسمي يبقى المختصر المتداول');
});

test('«الرئاسة العامة لشؤون الحرمين الشريفين» جهة ثالثة مستقلة — لا تُدمج بجارتيها', () => {
  const gp = matchEntity('الرئاسة العامة لشؤون الحرمين الشريفين');
  assert.equal(gp.official_name, 'الرئاسة العامة لشؤون الحرمين الشريفين');
  assert.equal(gp.confidence, 'مؤكَّد');
  assert.equal(gp.exact, true);
  const gph = matchEntity('الهيئة العامة للعناية بشؤون المسجد الحرام والمسجد النبوي');
  const prh = matchEntity('رئاسة الشؤون الدينية بالمسجد الحرام والمسجد النبوي');
  assert.equal(gph.abbr, 'GPH');
  assert.equal(prh.abbr, 'PRH');
  // ثلاث جهات ⟵ ثلاثة سجلات. ربطها اسماً بديلاً كان سيجمع عملاء مختلفين في سجل واحد، ودمج
  // سجلَّي عميل لا رجعة فيه عملياً.
  assert.equal(new Set([gp.entity.id, gph.entity.id, prh.entity.id]).size, 3,
    'سجلٌّ ابتلع الآخر — الثلاث جهات متمايزة بأعمالها وتعاقداتها');
  // واسم كلٍّ منها المختصر يبقى عند صاحبه
  assert.equal(matchEntity('هيئة العناية بالحرمين').entity.id, gph.entity.id);
  assert.equal(matchEntity('رئاسة الشؤون الدينية').entity.id, prh.entity.id);
});

