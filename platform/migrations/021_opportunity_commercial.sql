-- ═══ الفرصة تحمل صفتها التجارية: نوع الارتباط ونوع الطرح ═══════════════════════════════════
--
-- بلسان المالك: «وأي فرصة… يا إنه تحطها اتفاقية إطارية، وبرضو يكون في مساحة تكون RFI أو RFP».
--
-- وهما سؤالان مختلفان عن الفرصة نفسها، وكلاهما يغيّر كيف تُقرأ:
--
--   • نوع الارتباط — أهي عملٌ محدَّد بقيمةٍ ومدة، أم **اتفاقية إطارية** يُسحَب منها لاحقاً؟
--     والفرق ليس تسميةً: قيمةُ الإطارية سقفٌ لا التزامٌ مؤكَّد، فجمعُها مع المشاريع المحدَّدة
--     في خطّ فرصٍ واحد يضخّم الرقم بما لن يتحقّق كلّه. تُميَّز أولاً كي يمكن فصلها متى لزم.
--
--   • نوع الطرح — كيف وصلت: استطلاع سوق (RFI)، أو طلب عرض (RFP)، أو طلب سعر (RFQ)، أو
--     تكليف مباشر، أو منافسة عامة. وهو ما يحدّد الجهد المطلوب واحتمال الفوز الواقعي:
--     استطلاعُ سوقٍ ليس فرصةً ناضجة، وتكليفٌ مباشر ليس منافسة.
--
-- ولماذا عمودان جديدان ولا يُعاد استعمال `source`: ذاك يحمل **من أين دخل الصفّ المنصةَ**
-- (إدخال مباشر · ملف إكسل · ترحيل الاستشارات · المساعد الذكي) — سؤالُ أثرٍ لا سؤال عمل.
-- وحشرُ معنى ثانٍ في عمودٍ قائم يُفقد الأول ولا يُحسن الثاني.
--
-- والعمودان بلا قيمة افتراضية عمداً: الفرص القائمة لا يعرف أحدٌ نوعَ طرحها اليوم، وكتابةُ
-- «تكليف مباشر» على مئةٍ وأربعٍ وثلاثين فرصةً بالتخمين تصنع رقماً يبدو معلوماً وليس كذلك.
-- الفراغ يقول «لم يُحدَّد بعد» بصدق، ويُملأ بيدٍ تعرف.

ALTER TABLE opportunity ADD COLUMN engagement_type   TEXT;
ALTER TABLE opportunity ADD COLUMN solicitation_type TEXT;

CREATE INDEX IF NOT EXISTS ix_opp_engagement   ON opportunity(engagement_type);
CREATE INDEX IF NOT EXISTS ix_opp_solicitation ON opportunity(solicitation_type);
