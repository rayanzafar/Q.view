-- ═══════════════════════ التعبئة الرجعية بخمسة عشر بالمئة ═══════════════════════
-- الترتيب داخل كل جدول مُلزَم: الصافي أولاً، ثم الضريبة من الفارق. عكسُه يحسب الضريبة من رقمٍ
-- لم يُكتب بعد. والشرط `IS NULL` في كل جملة يجعل الملف غير ضارٍّ لو أُعيد تشغيله بأي حال.

UPDATE invoice SET net_amount_halalas = COALESCE(amount_halalas, 0) * 100 / 115
 WHERE net_amount_halalas IS NULL;
UPDATE invoice SET vat_halalas = COALESCE(amount_halalas, 0) - net_amount_halalas
 WHERE vat_halalas IS NULL AND net_amount_halalas IS NOT NULL;

UPDATE contract SET net_value_halalas = COALESCE(value_halalas, 0) * 100 / 115
 WHERE net_value_halalas IS NULL;
UPDATE contract SET vat_halalas = COALESCE(value_halalas, 0) - net_value_halalas
 WHERE vat_halalas IS NULL AND net_value_halalas IS NOT NULL;

UPDATE contract_payment SET net_amount_halalas = COALESCE(amount_halalas, 0) * 100 / 115
 WHERE net_amount_halalas IS NULL;
UPDATE contract_payment SET vat_halalas = COALESCE(amount_halalas, 0) - net_amount_halalas
 WHERE vat_halalas IS NULL AND net_amount_halalas IS NOT NULL;

UPDATE revenue_line SET net_amount_halalas = COALESCE(amount_halalas, 0) * 100 / 115
 WHERE net_amount_halalas IS NULL;
UPDATE revenue_line SET vat_halalas = COALESCE(amount_halalas, 0) - net_amount_halalas
 WHERE vat_halalas IS NULL AND net_amount_halalas IS NOT NULL;

UPDATE collection SET net_amount_halalas = COALESCE(amount_halalas, 0) * 100 / 115
 WHERE net_amount_halalas IS NULL;
UPDATE collection SET vat_halalas = COALESCE(amount_halalas, 0) - net_amount_halalas
 WHERE vat_halalas IS NULL AND net_amount_halalas IS NOT NULL;

UPDATE purchase_order SET net_amount_halalas = COALESCE(amount_halalas, 0) * 100 / 115
 WHERE net_amount_halalas IS NULL;
UPDATE purchase_order SET vat_halalas = COALESCE(amount_halalas, 0) - net_amount_halalas
 WHERE vat_halalas IS NULL AND net_amount_halalas IS NOT NULL;

