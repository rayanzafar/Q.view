// مرجع الجهات السعودية — واليقين الذي يحتاج برهاناً.
//
// هذا الملف يحرس **الأخطاء التي وقعت فعلاً** في أول جولة مطابقة، لا أخطاءً متخيَّلة. جولة
// بتشابه الكلمات وحده أنتجت على بيانات حقيقية:
//   • «الأمن العام» ⟵ «الهيئة الوطنية للأمن السيبراني» — وعلى الأولى ٢٧٠ مليون ريال.
//   • «ميناء جدة الإسلامي» ⟵ «جامعة جدة» — لاشتراكهما في كلمة «جدة».
//   • «مجموعة د. سليمان الحبيب الطبية» ⟵ «مجموعة السعودية» — لاشتراكهما في «مجموعة».
//   • «قطاع الحلول — داخلي» ⟵ «مجلس الوزراء» — لتطابق شرطتين على اختصار فارغ «—».
// كلها كانت ستُنفَّذ لو صُنِّفت «مؤكَّدة». فالفحوص أدناه تُثبت أن أياً منها **لا يُصنَّف
// مؤكَّداً**، وأن المؤكَّد الحقيقي يبقى مؤكَّداً.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { matchEntity, entityCount, normalizeEntityName } from '../../src/core/org/entity-registry.js';

test('المرجع محمَّل — وبلا مرجع لا مطابقة أصلاً', () => {
  assert.ok(entityCount() > 300, `عدد الجهات أقل مما ينبغي (${entityCount()})`);
});

// ── اليقين ──────────────────────────────────────────────────────────────────
test('الاسم الرسمي حرفاً بحرف: مؤكَّد ولا يُقترح عليه تغيير', () => {
  const m = matchEntity('وزارة الاقتصاد والتخطيط');
  assert.equal(m.confidence, 'مؤكَّد');
  assert.equal(m.exact, true, 'هو الصواب أصلاً — اقتراح تغييره ضجيج');
  assert.equal(m.abbr, 'MEP');
});

test('العلامة التجارية بين قوسين تُنزَع حين تخصّ الجهة نفسها', () => {
  // «موانئ» اختصار الهيئة العامة للموانئ نفسها، فالقوسان زينة لا تمييز.
  const m = matchEntity('الهيئة العامة للموانئ (موانئ)');
  assert.equal(m.confidence, 'مؤكَّد');
  assert.equal(m.official_name, 'الهيئة العامة للموانئ');
  assert.equal(m.exact, false, 'يُقترح توحيده على الاسم الرسمي');
});

test('قوسان بعلامة لا تخصّ الجهة لا يُنزَعان', () => {
  const m = matchEntity('وزارة الاقتصاد والتخطيط (فرع الرياض)');
  assert.notEqual(m?.confidence, 'مؤكَّد',
    '«فرع الرياض» ليست علامة الوزارة — نزعها يساوي فرعاً بالجهة الأم');
});

test('«هدف» تصل إلى صندوق تنمية الموارد البشرية — وهو ما تعجز عنه مقارنة النصوص', () => {
  const m = matchEntity('هدف');
  assert.equal(m.confidence, 'مؤكَّد');
  assert.equal(m.official_name, 'صندوق تنمية الموارد البشرية');
  assert.equal(m.abbr, 'HRDF');
});

test('اختلاف الهمزة وحده لا يصنع جهةً ثانية', () => {
  const m = matchEntity('الجامعة السعودية الالكترونية');
  assert.equal(m.confidence, 'مؤكَّد');
  assert.equal(m.official_name, 'الجامعة السعودية الإلكترونية');
  assert.equal(normalizeEntityName('الالكترونية'), normalizeEntityName('الإلكترونية'));
});

// ── الأخطاء التي وقعت فعلاً ─────────────────────────────────────────────────
test('«الأمن العام» لا تُطابَق بالأمن السيبراني — الخطأ الذي كان سيمسّ ٢٧٠ مليوناً', () => {
  const m = matchEntity('الأمن العام');
  assert.notEqual(m?.official_name, 'الهيئة الوطنية للأمن السيبراني');
  if (m) assert.notEqual(m.confidence, 'مؤكَّد', 'وإن رُشِّحت فللمراجعة لا للتنفيذ');
});

test('«ميناء جدة الإسلامي» ليست «جامعة جدة» — رأس الاسم يمنع أصلاً', () => {
  const m = matchEntity('ميناء جدة الإسلامي');
  assert.notEqual(m?.official_name, 'جامعة جدة', 'ميناء ≠ جامعة مهما اشتركا في المدينة');
});

test('«مجموعة» المشتركة لا تجمع مستشفىً بشركة طيران', () => {
  const m = matchEntity('مجموعة د. سليمان الحبيب الطبية');
  assert.notEqual(m?.official_name, 'مجموعة السعودية');
});

test('الشرطة ليست اختصاراً — اختصار فارغ لا يطابق شيئاً', () => {
  for (const nm of ['قطاع الحلول — داخلي (رؤية الخبراء)', 'استدامة — مركز البحوث الزراعية']) {
    const m = matchEntity(nm);
    assert.notEqual(m?.official_name, 'مجلس الوزراء', `«${nm}» طابقت على «—» — اختصار فارغ`);
  }
});

test('ما ليس في المرجع يبقى بلا مقابل — لا أقرب جهة', () => {
  assert.equal(matchEntity('شركة الفا الرقمية'), null, 'جهة خاصة خارج المرجع');
  assert.equal(matchEntity(''), null);
  assert.equal(matchEntity(null), null);
});

test('اسم بلا رأس مؤسسي لا يدخل باب «للمراجعة» — وإلا طابق كل شيء', () => {
  const m = matchEntity('يسر المشاعر');
  assert.equal(m, null);
});

// ── درجة «للمراجعة»: تُعرَض ولا تُنفَّذ ─────────────────────────────────────
test('اسم ناقص من وزارة قائمة يُرشَّح للمراجعة لا لليقين', () => {
  const m = matchEntity('وزارة الشؤون الإسلامية');
  assert.ok(m, 'يُرشَّح');
  assert.equal(m.confidence, 'للمراجعة',
    'الاسم الرسمي «… والدعوة والإرشاد» — والزيادة قد تعني جهة أخرى، فالقرار بشري');
  assert.match(m.reason_ar, /يحتاج تأكيدك/);
});

// ── تصحيحات المالك على المرجع المستورَد ─────────────────────────────────────
// المرجع ملفٌ بشريّ، وفيه خطآن أمسكهما المالك — أحدهما **بعد** أن نُفِّذ على البيئة الحيّة.
// تسجيلهما هنا يمنع عودتهما مع أي تحديث للملف، ويحفظ سببهما لمن يقرأ بعد سنة.
test('«الخطوط السعودية» ليست اسماً بديلاً لـ«مجموعة السعودية» — التابع ليس مالكه', () => {
  const m = matchEntity('الخطوط السعودية');
  assert.notEqual(m?.official_name, 'مجموعة السعودية',
    'شركة الطيران غير الكيان القابض — والخلط بينهما أعاد تسمية عميل خطأً على البيئة الحيّة');
});

test('اسم سدايا كما اعتمده المالك — والاسم القديم يبقى بديلاً فلا يُنشئ سجلاً ثانياً', () => {
  const byBrand = matchEntity('سدايا');
  assert.equal(byBrand.official_name, 'الهيئة العامة للذكاء الاصطناعي والبيانات');
  const byOld = matchEntity('الهيئة السعودية للبيانات والذكاء الاصطناعي');
  assert.ok(byOld, 'من يكتب الاسم القديم يصل للجهة نفسها');
  assert.equal(byOld.official_name, 'الهيئة العامة للذكاء الاصطناعي والبيانات');
  assert.equal(byOld.entity.id, byBrand.entity.id, 'سجل واحد لا سجلان');
});

test('كل تصحيح للمالك مسجَّل بسببه — لا تغيير صامت على مرجعه', async () => {
  const { readFileSync } = await import('node:fs');
  const ref = JSON.parse(readFileSync(new URL('../../seed/saudi-entities.json', import.meta.url), 'utf8'));
  const fixes = ref._meta?.owner_corrections || [];
  assert.ok(fixes.length >= 2, 'التصحيحات محفوظة في الملف نفسه');
  for (const f of fixes) {
    assert.ok(f.reason && f.reason.length > 20, `تصحيح بلا سبب مكتوب: ${f.entity}`);
    assert.ok(f.change, `تصحيح بلا وصف لما تغيّر: ${f.entity}`);
  }
});
