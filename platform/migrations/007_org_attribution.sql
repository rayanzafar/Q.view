-- 007: الإسناد الإداري — نسبة العمل إلى الإدارة المالكة له.
--
-- المشكلة التي يغلقها هذا الملف: الجداول التشغيلية تحمل `sector_id` فقط، فتتكدّس المشاريع والفرص
-- على «قطاع الحلول» ككتلة واحدة بينما جزء كبير منها يخص إدارة بعينها (مثل «إدارة المدن الذكية»)،
-- وتبقى الإدارات في الشجرة بلا عمل ومدير الإدارة بلا إجابة على سؤال واحد من أسئلته اليومية.
--
-- ما استُبعد من هذه الموجة عمداً (لئلا يُعاد إدخاله بلا قرار):
--   • جدول «شركة» وعمود company_id على القطاع: لم يطلبهما المالك، وتوجيهه كان «القطاعات أربعة،
--     ركّز». تمثيل الكيانات المستقلة قرار مالك بموجة خاصة، لا افتراض داخل ترحيلة.
--   • عمودا valid_from/valid_to للتأريخ الفعّال: **شكل خاطئ للغرض**. المعيار (Workday و
--     SuccessFactors) سطر لكل نسخة من السجل، لا عمودا تاريخ على السطر الحالي — فعمودان هنا
--     يوهمان بقدرة لا يستطيع النموذج تقديمها. يُبنى التأريخ بشكله الصحيح في موجة مستقلة.
-- الحجة المقابلة مفهومة (الترحيلات مجمَّدة بعد النشر، فالتجميع يوفّر موجة ثانية) — لكن عموداً
-- ميتاً في مخطط حيّ كلفته دائمة، وحقلاً بشكل خاطئ أسوأ من غيابه.
--
-- توافق كامل مع القائم (backward compatible):
--   • كل عمود جديد اختياري وبلا قيمة افتراضية إلزامية ⟵ الصفوف القائمة تبقى كما هي، وكل إدخال
--     قائم لا يذكر العمود يظل يعمل بلا تعديل، ولا تنكسر أي شاشة منشورة.
--   • لا حذف ولا إعادة تسمية لأي عمود أو فهرس قائم.
--   • لا Backfill للإسناد إطلاقاً: نسبة العمل إلى إدارة قرار بشري مسؤول يتخذه المسؤول من الشاشة،
--     والتخمين الصامت من اسم المشروع أسوأ من الفراغ الظاهر.
--
-- قابلية النقل (SQLite + Postgres عبر pgify في scripts/migrate.js):
--   • النمط المتّبع في هذا المستودع هو `ALTER TABLE … ADD COLUMN` مجرّداً (انظر 002 و006).
--     صيغة `ADD COLUMN IF NOT EXISTS` **لا يدعمها SQLite بأي إصدار** (تدعمها Postgres وحدها)،
--     وmigrate.js لا يعيد كتابة الجُمل بين المحرّكين (يحوّل الأنواع فقط: INTEGER→BIGINT و
--     REAL→DOUBLE PRECISION)، فلو كتبناها هنا لانكسر التهجير على SQLite (المحرّك المستخدم في
--     التطوير والاختبارات). التكرار مستحيل أصلاً: migrate.js يسجّل كل ملف في schema_migration
--     ولا يعيد تطبيقه — فالإدمبوتنسي على مستوى الملف لا على مستوى الجملة.
--   • REFERENCES مسموح في ADD COLUMN على SQLite ما دامت القيمة الافتراضية NULL — وهي كذلك.
--   • `CREATE TABLE/INDEX IF NOT EXISTS` و`ON CONFLICT DO NOTHING` صالحة على المحرّكين معاً.
--   • لا علامة استفهام لاتينية في هذا الملف: طبقة الوصول تستبدلها بمعاملات مربوطة على Postgres.

-- ────────────────────── (٢) الإدارة المالكة للعمل ──────────────────────
-- إدارة واحدة مالكة لكل صف (لا توزيع نسبي ولا تعدد إدارات): المسؤولية المشتركة مسؤولية ضعيفة،
-- وتعدد الملكية يُنتج ازدواج احتساب يستحيل شرحه لغير المختص. أما «الإدارة المنفّذة» فتبقى مشتقة
-- من إدارة الموظف (employee.department_id القائم) — بُعد ثانٍ لا نسخة ثالثة من الحقيقة.
ALTER TABLE project     ADD COLUMN department_id TEXT REFERENCES department(id);
ALTER TABLE opportunity ADD COLUMN department_id TEXT REFERENCES department(id);
ALTER TABLE allocation  ADD COLUMN department_id TEXT REFERENCES department(id);

-- ───────────────────────────── (٣) الفهارس ─────────────────────────────
-- كل شاشات هذه الحارة تقرأ إما «عمل هذه الإدارة» أو «عمل هذا القطاع بلا إدارة».
CREATE INDEX IF NOT EXISTS ix_project_dept ON project(department_id);
CREATE INDEX IF NOT EXISTS ix_opp_dept     ON opportunity(department_id);
CREATE INDEX IF NOT EXISTS ix_alloc_dept   ON allocation(department_id);
-- عدّ موظفي الإدارة يجري في شجرة الهيكل وفي تجميع الإدارة معاً بلا فهرس حتى اليوم.
CREATE INDEX IF NOT EXISTS ix_emp_dept     ON employee(department_id);
