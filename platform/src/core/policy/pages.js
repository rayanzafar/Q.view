// سياسة فتح الصفحات — **من يفتح ماذا**. مكانها `core` لا `web` لأنها قرار صلاحيات لا عرض:
// يستهلكها العرض (القائمة الجانبية وحارس 403) ويستهلكها غير العرض (الدليل والبحث). وضعها في
// `web` أجبر مستهلكيها على أحد سيّئين: إما استيراد `web` من داخل `modules` (عكس اتجاه الطبقات
// المعلن)، أو نسخ الشروط يدوياً — وهو ما فعله البحث بأربعة شروط، وأول انحراف في نسخة منها
// يُنتج وعداً بشاشة يردّها النظام. المصدر هنا واحد، فلا انعكاس ولا نسخة ثانية.
// لا تستورد هذه الوحدة إلا من `core` كي تبقى صالحة لكل الطبقات.
import { can, effectiveScope } from '../rbac/index.js';

const IO_TYPES_READ = ['opportunity', 'project', 'client', 'employee', 'allocation', 'revenue'];

// ── من يرى «أداء الشركة»؟ سؤالٌ عن المنح لا عن اتساع نافذة البيانات ──────────
// كان الجواب عمود `scope` في حساب المستخدم وحده. وهذا العمود يجيب سؤالاً آخر تماماً: «كم
// يبلغ عرض نافذة بياناته؟» — لا «هل أداء الشركة من شأنه؟». الخلط بينهما ليس نظرياً: منح
// «المشتريات» شركية بحقّ (الموردون وأوامر الشراء عبر الشركة كلها) فحساب الدور «شركة»
// بالضرورة، فكان يفتح لوحة القيادة ومحفظة المشاريع وأرقام الإيراد والمبيعات والمستهدفات —
// وهو لا يملك منح تقرير ولا مؤشر ولا هامش ولا كلفة. ومثلها أي حساب وُسِّعت نافذته لغرض
// تشغيلي: الاتساع كان يُترجَم رتبةً قيادية بلا أن يقرّر ذلك أحد.
//
// الجواب الصحيح يُقرأ من المنح: **من يقرأ تقارير الشركة أو مؤشراتها على مستوى الشركة**.
// ويُقرأ بـ`effectiveScope` لا بـ`can`: فـ`can(u,'read','report')` بلا صفٍّ هدف تعود true
// لمجرد وجود أي منح مطابق مهما ضاق نطاقه، فيمرّ بها قائد قطاع (تقارير قطاعه) ومدير مشروع
// (تقارير مشروعه) إلى شاشة الشركة. المطلوب هنا **اتساع المنح** لا وجوده.
//
// والشرط الثاني — نافذة بيانات شركية — ليس إعادةً للعطل بل وفاءٌ بوعد هذه الوحدة: شاشة
// القيادة تستدعي `companyOverview` وهي ترفض من نافذته أضيق من الشركة، فلو فُتح الباب على
// المنح وحدها لظهر في القائمة الجانبية رابطٌ يَعِد بشاشة يردّها النظام عند فتحها. الرتبة
// من المنح، والاتساع من الحساب، والشاشة تحتاجهما معاً.
//
// الهامش والكلفة ليسا مفتاح الباب بل حجابٌ داخل الشاشة: `companyOverview` تعيدهما مشروطين
// بـ`canSeeSensitive`، فمن يدخل بلا منحهما يرى الإيراد والمبيعات ولا يرى ربحاً ولا كلفة.
export function seesCompanyPerformance(user) {
  if (!user) return false;
  const leadershipGrant = effectiveScope(user, 'read', 'report') === 'company'
    || effectiveScope(user, 'read', 'kpi') === 'company';
  return leadershipGrant && user.scope === 'company';
}

// من يفتح الصفحة؟ (مفاتيح PAGES في routes.js)
export const PAGE_ACCESS = {
  ceo: (u) => seesCompanyPerformance(u),
  portfolio: (u) => seesCompanyPerformance(u),
  sector: (u) => can(u, 'read', 'project') || can(u, 'read', 'opportunity'),
  opportunities: (u) => can(u, 'read', 'opportunity'),
  'my-opportunities': (u) => can(u, 'read', 'opportunity'),
  projects: (u) => can(u, 'read', 'project'),
  // العملاء: منح قراءة العميل أولاً، ثم منفذ القيادة. المنفذ موجود لأن شاشة العملاء تعرض
  // تركّز الإيراد وحصص أكبر العملاء من إيراد الشركة — وهي أرقام قيادية يقرؤها من يقرأ تقارير
  // الشركة حتى لو خلت قائمة منحه من مورد «العميل». وكان المنفذ مفتوحاً على اتساع النافذة
  // وحدها، فتدخل منه المشتريات: قائمة عملاء فارغة (لا منح لها) وفوقها إيراد الشركة كاملاً.
  clients: (u) => can(u, 'read', 'client') || seesCompanyPerformance(u),
  tasks: () => true,
  // مُزالة بطلب المالك — لا تظهر في القائمة ولا تُفتح بالعنوان المباشر.
  timesheet: () => false,
  // «دليلي» صفحة شرح لكل من يدخل المنصة — لا شيء فيها يُحرس: محتواها نفسه مُرشَّح مسبقاً
  // بنفس بوابة الصلاحيات التي تسمح أو تمنع كل شاشة، فلا يصل المستخدم إلا لشرح ما يراه فعلاً.
  guide: () => true,
  approvals: (u) => ['admin', 'sector_lead', 'finance', 'department_manager', 'line_manager', 'approver', 'ceo_office'].includes(u.role_id),
  finance: (u) => can(u, 'read', 'invoice') || can(u, 'read', 'contract'),
  team: (u) => can(u, 'read', 'employee'),
  staffing: (u) => can(u, 'read', 'employee'),
  imports: (u) => u.role_id === 'admin' || ['client', 'employee', 'opportunity', 'project', 'allocation', 'revenue_line'].some((r) => can(u, 'read', r) || can(u, 'create', r) || can(u, 'update', r)),
  reports: (u) => can(u, 'read', 'report'),
  mail: (u) => ['admin', 'ceo_office'].includes(u.role_id),
  // بوابة الصفحة كانت تسأل عن **إنشاء** موظف بينما الشاشة قراءةٌ في أصلها، والخدمة تحتها
  // (orgTree) تفتح على «قراءة موظف». فكان مدير الإدارة ومدير مكتب الرئيس التنفيذي يُردّان عن
  // شجرةٍ بياناتُها مسموحة لهما أصلاً — بوابةٌ أضيق من كل خدمةٍ خلفها. المواءمة لا تكشف شيئاً
  // جديداً: أهداف القطاع المالية تُحجب ما لم يكن النطاق شركياً (orgTree)، والتوزيع والفحص لكل
  // منهما بوابته القطاعية، والتعديل خلف mayEdit وحده. الداخلون بها أربعة يملكون «قراءة موظف»:
  // مكتب الرئيس التنفيذي · مدير الإدارة · المدير المباشر · رئيس تطوير الأعمال.
  org: (u) => u.role_id === 'admin' || can(u, 'create', 'sector') || can(u, 'read', 'employee'),
  users: (u) => u.role_id === 'admin',
  audit: (u) => u.role_id === 'admin',
};
