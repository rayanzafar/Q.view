-- الجلسة تتدحرج مع العمل، ولا تنتهي في منتصف الجملة
--
-- كانت `expires_at` تُكتب مرةً واحدة لحظة الدخول ولا تُلمَس بعدها أبداً: لا سطر واحد في
-- المنتج كله يقول `UPDATE session SET expires_at` — كل تحديثات الجدول تكتب `revoked_at`
-- (خروج، تغيير كلمة مرور، تعطيل، إنهاء جلسات، حذف حساب). أي أن الساعة تبدأ عند الدخول
-- ولا يعيدها شيء: من يعمل اثنتي عشرة ساعة متصلة يُطرَد وهو يكتب، ومن دخل مساءً يُطرَد
-- في صباحه. والقياس على البيانات الحيّة أكّده حرفياً: ١٥١٩ صفّاً من ١٥٢٩ فارقُها
-- ٧٢٠ دقيقة بالضبط — لا استثناء واحد.
--
-- ── لماذا عمودٌ واحد فقط ──────────────────────────────────────────────────────
-- التدحرج نفسه لا يحتاج مخزَّناً جديداً: `expires_at` تُمدَّد في مكانها، والسقف المطلق
-- يُحسب من `created_at` القائم أصلاً. العمود الوحيد المضاف هو **خانق الكتابة**: بلا
-- «متى لُمست آخر مرة» تصير كل نقرة كتابةً في القاعدة — والصفحة الواحدة عشرات الطلبات.
-- به تصير الكتابة مرةً كل بضع دقائق لكل مستخدم، والقراءة تبقى كما هي.
--
-- وهو مفيدٌ بذاته أيضاً: شاشة «إنهاء الجلسات» كانت تعرض جلسةً بلا أثر حياة، فلا يعرف
-- مدير النظام أيّها جهازٌ منسيٌّ وأيّها الجهاز الذي بين يدي صاحبه الآن.
--
-- ── إن فشل الإقلاع بـ«عمودٌ مكرَّر: last_seen_at» ─────────────────────────────
-- هذه الجملة وحدها غيرُ قابلة لإعادة التشغيل (`ADD COLUMN IF NOT EXISTS` تعرفها Postgres
-- ولا تعرفها SQLite، فلا تُكتب في المجموعة المحمولة). و`scripts/migrate.js` ينفّذ الملف
-- ثم يكتب صفَّ التتبّع في نداءين بلا معاملةٍ حولهما — فانقطاعٌ بينهما (قتلُ حاوية، إعادة
-- تشغيل) يترك العمود مضافاً والترحيلة غير مسجَّلة، فيُعاد تشغيل الملف عند الإقلاع التالي
-- فيفشل، وفشلُ الترحيلة قاتلٌ عمداً (boot.sh) — أي بيئةٌ لا تُقلع، لا ميزةٌ ناقصة.
-- العلاج دقيقة واحدة: سجِّل الترحيلة يدوياً ثم أعد الإقلاع.
--   INSERT INTO schema_migration (version, applied_at)
--   VALUES ('035_session_sliding.sql', '<الآن بصيغة ISO>');
ALTER TABLE session ADD COLUMN last_seen_at TEXT;

-- ── فهرسٌ على الانتهاء ────────────────────────────────────────────────────────
-- الجدول لم يُكنَس قط منذ أول إصدار: `DELETE FROM session` لا يظهر في `src/` ولا في
-- `scripts/`، وقد بلغ ١٥٢٩ صفّاً وفيه صفوفٌ من تموز. ويُغذّيه أكثر من الدخول: محرّك
-- التقارير يكتب صفّاً لكل تقرير لكل مستقبِل وتعليقُه يقول «cleaned by TTL» — ولا شيء
-- ينظّفها. والكنسة الدورية (المجدول، كل ساعة) تقرأ بهذا الفهرس لا بمسحٍ كامل.
--
-- وجلساتٌ تتدحرج تعيش أطول بطبعها، فالكنس صار شرطاً لا تحسيناً.
CREATE INDEX IF NOT EXISTS ix_session_expiry ON session(expires_at);

-- ── أثرُ حياةٍ للقائم ─────────────────────────────────────────────────────────
-- الجلسات القائمة يوم الترحيلة لا تعرف متى لُمست، فتُنسب إلى لحظة إنشائها: أقدمُ تقديرٍ
-- ممكن وأسلمُه — لا يمنح أحداً امتداداً لم يكسبه، وأول طلبٍ منه يصحّح الختم بنفسه.
UPDATE session SET last_seen_at = created_at WHERE last_seen_at IS NULL;
