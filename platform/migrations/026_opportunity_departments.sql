-- فرصةٌ تعمل عليها أكثر من إدارة
--
-- «ممكن الفرصة تتسكّن على أكثر من إدارة — هاتان الفرصتان تحت إدارة البيانات والذكاء الاصطناعي
-- وتحت إدارة المدن الذكية. فسجّلها، وخلّي مكان التسجيل ممكن أحطّ أكثر من إدارة أو قطاع يشتغل
-- على الفرصة» — بلسان المالك.
--
-- ── لماذا جدولٌ لا عمودٌ ثانٍ ────────────────────────────────────────────────
-- العمود الواحد (`opportunity.department_id`) يقول «إدارة واحدة» ولا يحتمل غيرها، وإضافةُ
-- `department_2` تُنشئ سؤالاً بلا جواب: وماذا لو كنّ ثلاثاً. والأسوأ أن كل استعلامٍ يجمع
-- بالإدارة يصير عليه أن يعرف عدد الأعمدة — فينسى أحدُها في موضعٍ فيختلّ الجمع بصمت.
--
-- ── والعمود الأصلي يبقى، وهو «الإدارة المسؤولة» ─────────────────────────────
-- لا يُلغى ولا يُستبدَل: هو الإدارة التي تُنسَب إليها الفرصة في المستهدفات وفي جمع آخر السنة —
-- ولو صار الجمع على «كل من يشارك» لصارت الفرصة الواحدة محسوبةً مرتين، ولانتفخ مجموع القطاع
-- على مجموع فرصه. فالمشاركة **رؤيةٌ وعمل**، والنسبة المالية واحدة لا تتجزأ.
-- والصفّ هنا للإدارات **المشاركة**: من يعمل على الفرصة ويراها في قوائمه، لا من تُحسب عليه.
--
-- ولا يُكرَّر الزوج: المفتاح الأساسي مركّب، فإضافة إدارةٍ مرتين لا تُنشئ صفّين يُعرضان مرتين.
CREATE TABLE IF NOT EXISTS opportunity_department (
  opportunity_id TEXT NOT NULL REFERENCES opportunity(id),
  department_id  TEXT NOT NULL REFERENCES department(id),
  created_at     TEXT NOT NULL,
  created_by     TEXT REFERENCES app_user(id),
  PRIMARY KEY (opportunity_id, department_id)
);

-- الفهرس على الإدارة: سؤال «ما الفرص التي تعمل عليها هذه الإدارة» هو ما تفتح به كل إدارةٍ
-- شاشتها، والمفتاح المركّب يبدأ بالفرصة فلا يخدم هذا الاتجاه.
CREATE INDEX IF NOT EXISTS ix_oppdept_dept ON opportunity_department(department_id);
