-- 010 — المهمة تحمل إدارتها وخطوتها التالية.
--
-- لماذا: الموجة 007 أسندت العمل إلى الإدارات على المشروع والفرصة والتسكين، وتركت **المهمة**
-- وحدها بلا عمود إدارة. فمهام الإدارة لا تُجمَّع ولا تظهر في تقرير إدارة، ومدير الإدارة لا
-- يستطيع أن يسأل «ما الذي يعمل عليه فريقي» إلا عبر القطاع كاملاً. وهذه أول ترحيلة تمسّ جدول
-- المهام منذ إنشائه.
--
-- و«الخطوة التالية» موجودة على الفرصة منذ البداية وتقود بيعها (وجودها من عدمه حالة معلَّمة في
-- تغذية «يحتاج انتباهك»)، ولا مقابل لها على المهمة — فالمهمة المتوقفة لا تقول ما الذي يحرّكها.
--
-- ملاحظتان تنفيذيتان مُلزمتان لهذا الملف:
--   • لا علامة استفهام لاتينية في أي سطر هنا ولا حتى داخل تعليق: الملف كله يمرّ على مُحوِّل
--     العلامات إلى ترقيم دولارات عند التشغيل على Postgres، فأي علامة تُفسد النص.
--   • لا وجود لـADD COLUMN IF NOT EXISTS في SQLite، فالإضافة صريحة بلا شرط، وحمايةُ التكرار
--     تأتي من سجل الترحيلات نفسه (ملف واحد يُطبَّق مرة واحدة).

ALTER TABLE task ADD COLUMN department_id TEXT REFERENCES department(id);
ALTER TABLE task ADD COLUMN next_step TEXT;

CREATE INDEX IF NOT EXISTS ix_task_dept ON task(department_id);

-- بلا أي تعبئة تلقائية: نسبة المهمة إلى إدارة قرار بشري، والتخمين الصامت من قطاع المشروع
-- يملأ التقارير بأرقام لا مصدر لها — وهو أسوأ من الفراغ الظاهر. نفس مبدأ الموجة 007.
