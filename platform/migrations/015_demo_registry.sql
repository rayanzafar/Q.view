-- ٠١٥ — سجلّ البيانات التجريبية: ما بُذر للعرض يُعرَف بعينه ويُمحى بأمرٍ واحد.
--
-- لماذا: المنصة تُملأ ببيانات سيناريوهات كي لا يرى المستخدم شاشاتٍ فارغة وهو يتعلّم — ثم يأتي
-- يومٌ يقول فيه المالك «امسحها». وبلا علامةٍ على كل صف، المحو يصير تخميناً: يُمشَّط الجدول
-- بحثاً عن اسمٍ ينتهي بـ«(تجريبي)» فيُمحى معه موظفٌ حقيقي سمّاه أحدهم كذلك، أو تبقى صفوفٌ
-- تجريبية لأن اصطلاح التسمية تغيّر بين دفعتين. وكلا الخطأين وقع في منتجات قبلنا.
--
-- القرار: **سجلٌّ خارجي** لا عمودٌ في كل جدول. البديل (إضافة عمود «تجريبي» إلى خمسين جدولاً)
-- يعني خمسين تعديل مخطط، وخمسين موضع نسيان، وحقلاً يظهر في كل استعلام لا يعني شيئاً لأحد.
-- أما السجل فجدولٌ واحد يقول: هذا الصف، في هذا الجدول، من هذه الدفعة. والمحو يقرأ منه فقط —
-- فلا يستطيع أن يمسّ صفاً لم يُسجَّل، مهما تشابهت الأسماء. الأمان هنا خاصيّة بنيوية لا حذر.
--
-- والدفعة (batch) هي وحدة المحو: «سيناريوهات الدليل» تُمحى وحدها ولا تُسقط معها بذرةَ الأدوار
-- ولا بيانات العرض القديمة. ولكل صف عنوانٌ مقروء (label) كي يُقرأ الكشف قبل المحو بعينٍ بشرية:
-- «ستُمحى ٤٢ مهمة و٧ فرص و٣ مشاريع» أوضح من «ستُمحى ٥٢ صفاً».
--
-- ترتيب المحو يُشتقّ من ترتيب الإدراج معكوساً (created_at تنازلياً): ما أُنشئ أخيراً يعتمد
-- غالباً على ما قبله، فمحوُه أولاً يتجنّب كسر المفاتيح الأجنبية بلا أن نكتب خريطة اعتماد يدوية
-- تتقادم مع أول جدول جديد.
--
-- ملاحظة تنفيذية مُلزمة (نفس قيد ٠١٠ و٠١٣ و٠١٤): لا علامة استفهام لاتينية في أي سطر هنا ولا
-- حتى داخل تعليق، لأن الملف كله يمرّ على مُحوِّل العلامات إلى ترقيم دولارات على Postgres.

CREATE TABLE IF NOT EXISTS demo_record (
  id          TEXT PRIMARY KEY,
  batch       TEXT NOT NULL,           -- وحدة المحو: كل بذرة تُعطي دفعتها اسماً
  table_name  TEXT NOT NULL,           -- الجدول الذي يسكنه الصف
  row_id      TEXT NOT NULL,           -- معرّف الصف نفسه
  label       TEXT,                    -- عنوان مقروء يظهر في كشف ما سيُمحى
  created_at  TEXT NOT NULL,
  purged_at   TEXT                     -- يبقى أثر المحو: من مُحي ومتى، فلا يختفي الخبر مع الخبر
);

-- المحو يقرأ الدفعة كاملةً مرتَّبةً بالأحدث أولاً — وهو الاستعلام الوحيد الساخن على هذا الجدول.
CREATE INDEX IF NOT EXISTS ix_demo_record_batch ON demo_record (batch, created_at);
-- ولا يُسجَّل الصف الواحد مرتين لو أُعيد تشغيل البذرة: التسجيل يصير عندها لا-عملية.
CREATE UNIQUE INDEX IF NOT EXISTS ux_demo_record_row ON demo_record (batch, table_name, row_id);
