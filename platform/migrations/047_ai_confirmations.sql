-- ٠٤٧ — تأكيدُ تغييرات المساعد داخل سند: الطلبُ يصل، والقرارُ يبقى هنا.
--
-- لماذا: كان التغيير القادم من مساعدٍ خارجي بخطوتين — معاينة تعطي رمزاً، ثم تنفيذٌ يقبل الرمز.
-- وهذا يحرس **الدقّة** (لا كتابة بلا معاينة، ولا معاينة تُطبَّق مرتين، ولا رمز يعيش أبداً)، لكنه
-- لا يحرس **الموافقة**: من رأى المعاينة هو المساعد لا صاحب الحساب. فلو اختصر المساعدُ العرض
-- ونادى التنفيذ في اللحظة نفسها، لكُتب التغيير وصاحبُ الحساب لم يقرأ حرفاً. ونافذةُ الإذن في
-- برنامج المساعد تقول «يريد استعمال أداةً في سند» ولا تقول ماذا سيتغيّر — فالموافقة عليها
-- موافقةٌ على فتح باب، لا على مضمون ما يعبره.
--
-- فصار التنفيذ القادم من مساعدٍ خارجي **يتوقّف** ويُسجَّل طلباً ينتظر: يفتح صاحبُ الحساب صفحة
-- «تغييرات تنتظر تأكيدك» في سند، يقرأ قبل/بعد بتفصيله، ثم يؤكّد أو يرفض بيده. الكتابةُ تقع
-- بضغطته هو داخل المنصة، لا بنداء أداةٍ في نافذة أخرى.
--
-- الأعمدة تجيب أسئلة الصفحة نفسها: بأي أداةٍ يُنفَّذ هذا الطلب بعد التأكيد (apply_tool)، ومن
-- طلبه من المساعدين المرتبطين — اسمُه لتقرأه الصفحة ومعرّفُه ليبقى في أثر التدقيق — ومتى بُتَّ
-- فيه تأكيداً أو رفضاً (decided_at). والرفضُ حدثٌ مؤرَّخ مثل التأكيد: «لم يُنفَّذ» جوابٌ يُقرأ
-- في السجل، لا فراغٌ يُفسَّر.
--
-- ومعرّفُ العميل يُحفظ لسببٍ واحد: الكتابةُ تقع بضغطةٍ داخل سند، فلولا حفظُه لضاعت نسبةُ العمل
-- إلى المساعد الذي طلبه، وصار الأثرُ يقول «فعلها صاحبُ الحساب» وحدها. من طلب ومن أذن كلاهما
-- يُكتبان: الطلبُ من المساعد، والإذنُ من الإنسان.
--
-- ملاحظة تنفيذية مُلزمة لهذا الملف (نفس قيد الترحيلتين ٠١٠ و٠١٣): لا علامة استفهام لاتينية في
-- أي سطر هنا ولا حتى داخل تعليق، لأن الملف كله يمرّ على مُحوِّل العلامات إلى ترقيم دولارات عند
-- التشغيل على Postgres فيُفسد النص. وإن لزمت علامة استفهام في نصٍّ عربي فالعلامة العربية «؟» هي
-- المستعملة. ولا وجود لـADD COLUMN IF NOT EXISTS في SQLite، فالإضافة صريحة بلا شرط، وحمايةُ
-- التكرار من سجل الترحيلات نفسه (ملف واحد يُطبَّق مرة واحدة).

ALTER TABLE ai_activity_log ADD COLUMN apply_tool TEXT;
ALTER TABLE ai_activity_log ADD COLUMN asked_by_client TEXT;
ALTER TABLE ai_activity_log ADD COLUMN asked_by_client_id TEXT;
ALTER TABLE ai_activity_log ADD COLUMN decided_at TEXT;

