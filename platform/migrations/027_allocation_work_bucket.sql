-- تسكينٌ على عملٍ داخلي، لا على مشروعٍ وحده
--
-- «في التسكين مو شرط يكون على مشروع … وبرضو ممكن أسكّن على مشروع أو أسكّن على
--  تطوير أعمال · تطوير منتجات · إدارة مشاريع» — بلسان المالك.
--
-- ── ما كان يقع قبل هذا العمود ────────────────────────────────────────────────
-- كل تسكينٍ في المنصة مربوطٌ بمشروع. ومن يقضي نصف شهره في تطوير الأعمال أو في إدارة مكتب
-- المشاريع لا موضع له في اللوحة: يُقرأ «بلا تسكين» وهو مشغول، فيُرشَّح لعملٍ جديد ويُحمَّل
-- فوق طاقته. أو يُخترَع له «مشروع داخلي» صوري فيدخل المحفظة ويُحسب في تقارير المشاريع.
-- والحالتان تكذبان على شاشةٍ يُتَّخذ بها قرارُ إسنادٍ حقيقي.
--
-- ── ولماذا عمودٌ على التسكين لا جدولُ «مشاريع داخلية» ────────────────────────
-- قرار مالكٍ سابق مكتوبٌ في المعجم: «لا كيان اسمه مشاريع داخلية». والعمل الداخلي ليس مشروعاً:
-- لا عميل له ولا عقد ولا مخرجات ولا نسبة إنجاز — وصفٌّ في `project` يجرّه إلى كل شاشةٍ تجمع
-- المحفظة وتحسب القيمة والإيراد. أما هنا فهو ما هو: **حجزٌ من وقت الشخص باسمٍ معلوم**، يُقرأ
-- في لوحة الطاقة وحدها ولا يظهر في المحفظة إطلاقاً.
--
-- والمفتاح نصٌّ قصير (bd · product · pmo) وتسميته العربية في المعجم — نفس ما يفعله «نوع العمل»
-- في تسجيل الوقت: القاعدة في الخدمة، والكلمة في المعجم، ولا تنعكس الطبقتان.
--
-- والعمود يبقى فارغاً في كل صفٍّ قائم: التسكين على مشروع هو الحال الأصل، وفراغُ العمود يعني
-- «هذا تسكين مشروع» بلا ترحيل صفٍّ واحد.
ALTER TABLE allocation ADD COLUMN work_bucket TEXT;

-- سؤال «كم من وقت الشركة يذهب إلى تطوير الأعمال هذه السنة» يُسأل بالبند لا بالشخص.
CREATE INDEX IF NOT EXISTS ix_alloc_bucket ON allocation(work_bucket);
