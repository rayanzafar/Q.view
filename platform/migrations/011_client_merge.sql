--
-- الجهة الواحدة كانت تُسجَّل أكثر من مرة، وانقسامها يتبع قطاع EVC المنفِّذ: «وزارة الاقتصاد
-- والتخطيط» على قطاع الحلول و«… - الديوان العام» على قطاع الاستشارات — وهما وزارة واحدة.
-- وأثره ليس تجميلياً: تركّز العميل، وأعمار ديونه، وخط فرصه، وتاريخ علاقته — كلها تُقسَم
-- نصفين فيقرأ المالك جهتين متوسطتين بدل جهة كبيرة واحدة.
--
-- العمود يجعل الدمج **مرئياً وقابلاً للعكس** بدل أن يكون حذفاً ناعماً صامتاً: الصفّ المدموج
-- يبقى محفوظاً ويشير إلى من ورثه، فيُعاد فتحه بتفريغ العمود وإزالة ختم الحذف. ومن يبحث
-- بالاسم القديم يمكن توجيهه إلى الجهة الباقية بدل «لا نتائج».
ALTER TABLE client ADD COLUMN merged_into_client_id TEXT REFERENCES client(id);

CREATE INDEX IF NOT EXISTS ix_client_merged_into ON client(merged_into_client_id);
