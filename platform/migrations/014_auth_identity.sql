-- ٠١٤ — هوية الدخول: رمزٌ يصل إلى البريد بدل كلمة مرور، وبريدٌ مطبَّع يصلح معرّفاً.
--
-- لماذا: الدخول اليوم باسم مستخدم وكلمة مرور، والبريد ليس معرّف دخول أصلاً. ومع فتح المنصة
-- لكل موظفي EVC صار ذلك عبئاً بلا مقابل: كلمةٌ تُنسى وتُشارَك وتُعاد تعيينها يدوياً — ولا
-- مسار استعادة في المنصة إطلاقاً. والرمز المؤقّت يزيل السرّ الدائم من المعادلة كلها.
--
-- الرمز يُخزَّن **مُجزَّأً** لا نصاً، بنفس دالة كلمة المرور. والسبب ليس شكلياً: جدولٌ فيه رموز
-- دخولٍ حيّة نصاً هو مفتاحٌ لكل حسابات الشركة لمن قرأ نسخةً احتياطية واحدة. ولأنه مُجزَّأ فلا
-- يمكن استرجاعه لعرضه على مشرف — وهذا مقصود، فالمشرف لا يحتاج رمز غيره.
--
-- والاستهلاك ذرّي: تحديثٌ مشروط واحد (WHERE consumed_at IS NULL AND expires_at > …) يقرّر
-- من ظفر بالرمز — نفس مزلاج معاينة المساعد. بلا ذلك يقبل طلبان متزامنان الرمز نفسه.
--
-- وتفرّد البريد: القيد الحالي على `email` فريدٌ لكنه حسّاس لحالة الأحرف، فـA@evc.sa
-- وa@evc.sa حسابان مختلفان — وفي دخولٍ مفتاحُه البريد يصير ذلك بابَ التباس لا تفصيلَ تنسيق.
--
-- ملاحظة تنفيذية مُلزمة (نفس قيد ٠١٠ و٠١٣): لا علامة استفهام لاتينية في أي سطر هنا ولا حتى
-- داخل تعليق، لأن الملف كله يمرّ على مُحوِّل العلامات إلى ترقيم دولارات على Postgres فيُفسد
-- النص. والعلامة العربية «؟» هي المستعملة عند اللزوم.

-- رموز الدخول لمرة واحدة. الغرض إمّا دخولٌ عادي أو تفعيل دعوة جديدة — والفرق مهم لأن رمز
-- الدعوة يفعّل حساباً معطّلاً بينما رمز الدخول لا يغيّر حالة الحساب أبداً.
CREATE TABLE IF NOT EXISTS login_code (
  id           TEXT PRIMARY KEY,
  user_id      TEXT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
  code_hash    TEXT NOT NULL,               -- scrypt$... — لا يُخزَّن الرمز نصاً أبداً
  purpose      TEXT NOT NULL DEFAULT 'signin', -- signin | invite
  expires_at   TEXT NOT NULL,
  consumed_at  TEXT,                        -- ختم الاستهلاك: غير فارغ يعني أن الرمز حُرق
  attempts     INTEGER NOT NULL DEFAULT 0,  -- محاولات خاطئة على هذا الرمز تحديداً
  ip           TEXT,
  created_at   TEXT NOT NULL
);

-- المزلاج الذرّي يبحث عن رمز المستخدم غير المستهلَك: هذان العمودان شرط التحديث المشروط.
CREATE INDEX IF NOT EXISTS ix_login_code_live ON login_code(user_id, consumed_at);
-- تنظيف الرموز المنتهية يمسح بالصلاحية، وطلبُ رمزٍ جديد يبطل سابقَه بالمستخدم.
CREATE INDEX IF NOT EXISTS ix_login_code_expiry ON login_code(expires_at);

-- تفرّدُ البريد بلا حساسية لحالة الأحرف — على **التعبير** لا على عمودٍ مرآة.
-- عمودٌ مرآة (email_normalized) كان سينحرف أوّلَ مرة يكتب فيها كودٌ عمودَ email وحده،
-- وانحرافُ مفتاحِ الدخول لا يظهر إلا يوم يعجز موظف عن الدخول. التعبير لا ينحرف أبداً.
-- والقيم الفارغة متعددة مسموحة على المحرّكين — حسابٌ بلا بريد يبقى قائماً (المدير
-- الإنتاجي الأول ليس له بريد بعد).
CREATE UNIQUE INDEX IF NOT EXISTS ux_app_user_email_ci ON app_user(lower(trim(email)));

-- طريقة الدخول الأخيرة لكل حساب: تُقرأ في شاشة إدارة الهوية كي يرى المشرف كيف يدخل الناس
-- فعلاً — لا كيف يُفترض أن يدخلوا. القيمة إمّا password أو otp أو microsoft لاحقاً.
ALTER TABLE app_user ADD COLUMN last_login_method TEXT;
